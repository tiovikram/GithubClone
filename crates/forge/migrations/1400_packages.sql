-- Packages (area packages): the OCI container registry (`/v2/`), the npm registry (`/npm/`) and
-- the REST packages API. Package content lives in object storage, content-addressed by sha256
-- (`packages/blobs/sha256/<hex>`): image layers, configs, manifests and npm tarballs alike.

-- A package in a user's or organization's namespace. Deleting a package is a soft delete
-- (restorable for 30 days, then purged by `forge gc`); the name is free again right away.
CREATE TABLE packages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    package_type  TEXT NOT NULL CHECK (package_type IN ('npm', 'maven', 'rubygems', 'docker', 'nuget', 'container')),
    name          TEXT NOT NULL,
    visibility    TEXT NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public', 'internal')),
    -- Linked repository (`org.opencontainers.image.source` label, package.json `repository`).
    repo_id       BIGINT REFERENCES repositories(id) ON DELETE SET NULL,
    -- Whether access is inherited from the linked repository (GitHub's default).
    inherit_access BOOLEAN NOT NULL DEFAULT TRUE,
    creator_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ,
    deleted_by    BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX packages_active_name ON packages (owner_id, package_type, lower(name)) WHERE deleted_at IS NULL;
CREATE INDEX packages_owner ON packages (owner_id, package_type, id);
CREATE INDEX packages_repo ON packages (repo_id) WHERE repo_id IS NOT NULL;

-- A version: a container manifest (name = its digest) or an npm version (name = the semver).
CREATE TABLE package_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id  BIGINT NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    -- Container: the manifest media type. npm: the tarball content type.
    media_type  TEXT NOT NULL DEFAULT '',
    -- Digest of the version's own object (manifest bytes / npm tarball) in the blob store.
    digest      TEXT NOT NULL,
    size        BIGINT NOT NULL DEFAULT 0,
    -- Container: {config_digest, artifact_type, subject, annotations, platform}. npm: the version
    -- document (package.json fields + dist).
    metadata    JSONB NOT NULL DEFAULT '{}',
    description TEXT,
    license     TEXT,
    creator_id  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ,
    deleted_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    UNIQUE (package_id, name)
);
CREATE INDEX package_versions_package ON package_versions (package_id, id);

-- Container tags and npm dist-tags.
CREATE TABLE package_tags (
    package_id  BIGINT NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
    tag         TEXT NOT NULL,
    version_id  BIGINT NOT NULL REFERENCES package_versions(id) ON DELETE CASCADE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (package_id, tag)
);
CREATE INDEX package_tags_version ON package_tags (version_id);

-- Objects of the content-addressed blob store (digest `sha256:<hex>`).
CREATE TABLE package_blobs (
    digest        TEXT PRIMARY KEY,
    size          BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Bumped whenever a client is told the blob exists, so `forge gc` leaves blobs alone that a
    -- push in progress is about to reference from a manifest.
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Blobs a version references (its own manifest/tarball, config, layers, child manifests).
CREATE TABLE package_version_blobs (
    version_id  BIGINT NOT NULL REFERENCES package_versions(id) ON DELETE CASCADE,
    digest      TEXT NOT NULL,
    PRIMARY KEY (version_id, digest)
);
CREATE INDEX package_version_blobs_digest ON package_version_blobs (digest);

-- Blobs uploaded (or mounted) into a container repository `owner/name` that no manifest
-- references yet. Keyed by name, not package: the package row is created by the first manifest.
CREATE TABLE package_repo_blobs (
    owner_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    digest        TEXT NOT NULL,
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (owner_id, name, digest)
);

-- Blob upload sessions (OCI distribution spec). Each PATCH chunk is its own object under
-- `packages/uploads/<id>/`; the PUT that completes the upload assembles and verifies them.
CREATE TABLE package_uploads (
    id            TEXT PRIMARY KEY,
    owner_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    user_id       BIGINT REFERENCES users(id) ON DELETE CASCADE,
    size          BIGINT NOT NULL DEFAULT 0,
    parts         TEXT[] NOT NULL DEFAULT '{}',
    -- Digest of the content when it arrived as a single part (no re-read needed).
    single_digest TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
