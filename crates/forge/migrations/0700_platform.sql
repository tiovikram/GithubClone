-- Releases ---------------------------------------------------------------------------------
ALTER TABLE releases ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
-- At most one release per repo is explicitly marked latest (make_latest=true on publish).
ALTER TABLE releases ADD COLUMN is_latest BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX releases_repo_created ON releases (repo_id, created_at DESC, id DESC);
ALTER TABLE release_assets ADD COLUMN state TEXT NOT NULL DEFAULT 'uploaded';
ALTER TABLE release_assets ADD COLUMN digest TEXT;

-- Release asset blobs live at releases/{repo_id}/{asset_id}; when a repository is deleted,
-- queue that prefix for `forge gc` like its packs.
CREATE FUNCTION platform_trash_release_assets() RETURNS trigger AS $$
BEGIN
    INSERT INTO storage_trash (prefix) VALUES ('releases/' || OLD.id || '/') ON CONFLICT DO NOTHING;
    RETURN OLD;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER repositories_trash_release_assets AFTER DELETE ON repositories
    FOR EACH ROW EXECUTE FUNCTION platform_trash_release_assets();

-- Generic Postgres job queue ("standard queue"). Workers claim due jobs with
-- FOR UPDATE SKIP LOCKED and lease them by pushing run_at forward; a crashed worker's job
-- simply becomes due again when the lease expires.
CREATE TABLE jobs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue        TEXT NOT NULL,
    payload      JSONB NOT NULL,
    attempts     INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 6,
    run_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX jobs_run_at ON jobs (run_at);

-- Webhooks -----------------------------------------------------------------------------------
ALTER TABLE webhooks ADD COLUMN name TEXT NOT NULL DEFAULT 'web';
ALTER TABLE webhooks ADD COLUMN last_response JSONB NOT NULL DEFAULT '{"code": null, "status": "unused", "message": null}';
CREATE INDEX webhooks_repo ON webhooks (repo_id);
CREATE INDEX webhooks_org ON webhooks (org_id);

CREATE TABLE webhook_deliveries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hook_id          BIGINT NOT NULL REFERENCES webhooks(id) ON DELETE CASCADE,
    guid             TEXT NOT NULL,
    event            TEXT NOT NULL,
    action           TEXT,
    repo_id          BIGINT,
    payload          JSONB NOT NULL,
    redelivery       BOOLEAN NOT NULL DEFAULT FALSE,
    status           TEXT NOT NULL DEFAULT 'Pending',
    status_code      INT NOT NULL DEFAULT 0,
    duration         DOUBLE PRECISION NOT NULL DEFAULT 0,
    request_headers  JSONB,
    response_headers JSONB,
    response_body    TEXT,
    attempts         INT NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivered_at     TIMESTAMPTZ
);
CREATE INDEX webhook_deliveries_hook ON webhook_deliveries (hook_id, id DESC);

-- Activity events (GET /repos/{o}/{r}/events, /users/{u}/events, /events) ------------------
CREATE TABLE activity_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       TEXT NOT NULL,
    actor_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    repo_id    BIGINT REFERENCES repositories(id) ON DELETE CASCADE,
    org_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    payload    JSONB NOT NULL DEFAULT '{}',
    public     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX activity_events_repo ON activity_events (repo_id, id DESC);
CREATE INDEX activity_events_actor ON activity_events (actor_id, id DESC);
CREATE INDEX activity_events_org ON activity_events (org_id, id DESC);

-- Users & orgs -------------------------------------------------------------------------------
CREATE TABLE gpg_keys (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    primary_key_id      BIGINT REFERENCES gpg_keys(id) ON DELETE CASCADE,
    name                TEXT,
    key_id              TEXT NOT NULL,
    public_key          TEXT NOT NULL,
    raw_key             TEXT,
    emails              TEXT[] NOT NULL DEFAULT '{}',
    can_sign            BOOLEAN NOT NULL DEFAULT TRUE,
    can_encrypt_comms   BOOLEAN NOT NULL DEFAULT FALSE,
    can_encrypt_storage BOOLEAN NOT NULL DEFAULT FALSE,
    can_certify         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at          TIMESTAMPTZ
);
CREATE INDEX gpg_keys_user ON gpg_keys (user_id, id);
CREATE UNIQUE INDEX gpg_keys_user_key ON gpg_keys (user_id, key_id) WHERE primary_key_id IS NULL;

CREATE TABLE follows (
    follower_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    followee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id)
);
CREATE INDEX follows_followee ON follows (followee_id, follower_id);

CREATE TABLE teams (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    slug        TEXT NOT NULL,
    description TEXT,
    privacy     TEXT NOT NULL DEFAULT 'closed',
    permission  TEXT NOT NULL DEFAULT 'pull',
    parent_id   BIGINT REFERENCES teams(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (org_id, slug)
);

CREATE TABLE team_members (
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role    TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('member', 'maintainer')),
    PRIMARY KEY (team_id, user_id)
);

