CREATE INDEX deployment_statuses_dep ON deployment_statuses (deployment_id, id DESC);

-- Gists (stored in Postgres; no git backing) -------------------------------------------------
CREATE TABLE gists (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gist_id     TEXT NOT NULL UNIQUE,
    owner_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    description TEXT,
    public      BOOLEAN NOT NULL DEFAULT FALSE,
    fork_of     BIGINT REFERENCES gists(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX gists_owner ON gists (owner_id, updated_at DESC);
CREATE INDEX gists_public ON gists (updated_at DESC) WHERE public;

CREATE TABLE gist_files (
    gist_id  BIGINT NOT NULL REFERENCES gists(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content  TEXT NOT NULL,
    PRIMARY KEY (gist_id, filename)
);

CREATE TABLE gist_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gist_id      BIGINT NOT NULL REFERENCES gists(id) ON DELETE CASCADE,
    version      TEXT NOT NULL,
    user_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    additions    BIGINT NOT NULL DEFAULT 0,
    deletions    BIGINT NOT NULL DEFAULT 0,
    files        JSONB NOT NULL DEFAULT '{}',
    committed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX gist_history_gist ON gist_history (gist_id, id DESC);

CREATE TABLE gist_stars (
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    gist_id    BIGINT NOT NULL REFERENCES gists(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, gist_id)
);
