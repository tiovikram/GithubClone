-- Build-out area `repos` (repos, users, issues, gists, activity, codes-of-conduct,
-- dependency-graph). See docs/BUILDOUT.md.

-- Deployment environments -------------------------------------------------------------------
CREATE TABLE environments (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id                BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    name                   TEXT NOT NULL,
    wait_timer             INTEGER NOT NULL DEFAULT 0,
    prevent_self_review    BOOLEAN NOT NULL DEFAULT FALSE,
    -- [{type: "User"|"Team", id}]
    reviewers              JSONB NOT NULL DEFAULT '[]',
    -- NULL = all branches may deploy; otherwise protected_branches / custom_branch_policies.
    protected_branches     BOOLEAN,
    custom_branch_policies BOOLEAN,
    -- Ids of the wait-timer / required-reviewers / branch-policy protection rules (stable ids).
    wait_timer_rule_id     BIGINT,
    reviewers_rule_id      BIGINT,
    branch_rule_id         BIGINT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX environments_repo_name ON environments (repo_id, lower(name));
CREATE SEQUENCE environment_rule_ids;

CREATE TABLE environment_branch_policies (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT NOT NULL REFERENCES environments(id) ON DELETE CASCADE,
    name           TEXT NOT NULL,
    type           TEXT NOT NULL DEFAULT 'branch' CHECK (type IN ('branch', 'tag')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX environment_branch_policies_name ON environment_branch_policies (environment_id, type, name);

-- Custom deployment protection rules (a GitHub App gate on an environment).
CREATE TABLE environment_protection_rules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT NOT NULL REFERENCES environments(id) ON DELETE CASCADE,
    integration_id BIGINT NOT NULL,
    enabled        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (environment_id, integration_id)
);

-- Per-repository security / feature toggles -------------------------------------------------
CREATE TABLE repo_settings (
    repo_id                         BIGINT PRIMARY KEY REFERENCES repositories(id) ON DELETE CASCADE,
    vulnerability_alerts            BOOLEAN NOT NULL DEFAULT FALSE,
    automated_security_fixes        BOOLEAN NOT NULL DEFAULT FALSE,
    automated_security_fixes_paused BOOLEAN NOT NULL DEFAULT FALSE,
    immutable_releases              BOOLEAN NOT NULL DEFAULT FALSE,
    lfs_enabled                     BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at                      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE repo_custom_property_values (
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    property_name TEXT NOT NULL,
    value         JSONB NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (repo_id, property_name)
);

-- Old owner/name -> repository, so URLs keep working after a transfer (like GitHub).
CREATE TABLE repo_redirects (
    owner_login TEXT NOT NULL,
    name        TEXT NOT NULL,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (owner_login, name)
);
CREATE UNIQUE INDEX repo_redirects_lower ON repo_redirects (lower(owner_login), lower(name));

-- Ref activity (GET /repos/{o}/{r}/activity) ------------------------------------------------
CREATE TABLE repo_ref_activity (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    actor_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ref           TEXT NOT NULL,
    before        TEXT NOT NULL,
    after         TEXT NOT NULL,
    activity_type TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX repo_ref_activity_repo ON repo_ref_activity (repo_id, id DESC);

-- Ruleset evaluations of pushes (rule suites) and ruleset version history ------------------
CREATE TABLE rule_suites (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id           BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    org_id            BIGINT REFERENCES users(id) ON DELETE CASCADE,
    actor_id          BIGINT REFERENCES users(id) ON DELETE SET NULL,
    actor_name        TEXT NOT NULL DEFAULT '',
    before_sha        TEXT NOT NULL,
    after_sha         TEXT NOT NULL,
    ref               TEXT NOT NULL,
    result            TEXT NOT NULL,
    evaluation_result TEXT NOT NULL,
    rule_evaluations  JSONB NOT NULL DEFAULT '[]',
    pushed_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX rule_suites_repo ON rule_suites (repo_id, id DESC);
CREATE INDEX rule_suites_org ON rule_suites (org_id, id DESC);

CREATE TABLE ruleset_versions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruleset_id BIGINT NOT NULL REFERENCES rulesets(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL,
    actor_id   BIGINT,
    actor_type TEXT NOT NULL DEFAULT 'User',
    state      JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (ruleset_id, version_id)
);

-- Pages ---------------------------------------------------------------------------------------
CREATE TABLE pages_sites (
    repo_id        BIGINT PRIMARY KEY REFERENCES repositories(id) ON DELETE CASCADE,
    build_type     TEXT NOT NULL DEFAULT 'legacy' CHECK (build_type IN ('legacy', 'workflow')),
    source_branch  TEXT NOT NULL,
    source_path    TEXT NOT NULL DEFAULT '/',
    cname          TEXT,
    https_enforced BOOLEAN NOT NULL DEFAULT FALSE,
    public         BOOLEAN NOT NULL DEFAULT TRUE,
    status         TEXT,
    -- Object-storage prefix of the live site (pages/{repo_id}/{generation}/) and its commit.
    live_prefix    TEXT,
    live_commit    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE pages_builds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    status      TEXT NOT NULL DEFAULT 'queued',
    error       TEXT,
    pusher_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    commit      TEXT NOT NULL DEFAULT '',
    duration    INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX pages_builds_repo ON pages_builds (repo_id, id DESC);

CREATE TABLE pages_deployments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id             BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    status              TEXT NOT NULL DEFAULT 'deployment_in_progress',
    artifact_url        TEXT NOT NULL,
    environment         TEXT NOT NULL DEFAULT 'github-pages',
    pages_build_version TEXT NOT NULL,
    creator_id          BIGINT REFERENCES users(id) ON DELETE SET NULL,
    error               TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Users -----------------------------------------------------------------------------------------
CREATE TABLE user_emails (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    email      TEXT NOT NULL,
    verified   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX user_emails_email ON user_emails (lower(email));
CREATE INDEX user_emails_user ON user_emails (user_id, id);

CREATE TABLE social_accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider   TEXT NOT NULL,
    url        TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, url)
);

-- Issues ------------------------------------------------------------------------------------------
CREATE TABLE issue_comment_pins (
    issue_id   BIGINT PRIMARY KEY REFERENCES issues(id) ON DELETE CASCADE,
    comment_id BIGINT NOT NULL UNIQUE REFERENCES issue_comments(id) ON DELETE CASCADE,
    pinned_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    pinned_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- `blocked_id` is blocked by `blocking_id`.
CREATE TABLE issue_dependencies (
    blocked_id  BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    blocking_id BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (blocked_id, blocking_id),
    CHECK (blocked_id <> blocking_id)
);
CREATE INDEX issue_dependencies_blocking ON issue_dependencies (blocking_id);

-- Values of organization issue fields set on an issue (field definitions belong to the org).
CREATE TABLE issue_field_values (
    issue_id   BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    field_id   BIGINT NOT NULL,
    field_name TEXT NOT NULL,
    data_type  TEXT NOT NULL DEFAULT 'text',
    value      JSONB,
    option_id  BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (issue_id, field_id)
);

-- Gists ---------------------------------------------------------------------------------------------
CREATE TABLE gist_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gist_id    BIGINT NOT NULL REFERENCES gists(id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    body       TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX gist_comments_gist ON gist_comments (gist_id, id);

-- Notifications --------------------------------------------------------------------------------------
-- One thread per (user, subject). `subject_key` is e.g. "Issue:123", "Release:7".
CREATE TABLE notification_threads (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    repo_id            BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    subject_key        TEXT NOT NULL,
    subject_type       TEXT NOT NULL,
    subject_title      TEXT NOT NULL,
    subject_url        TEXT,
    latest_comment_url TEXT,
    reason             TEXT NOT NULL,
    unread             BOOLEAN NOT NULL DEFAULT TRUE,
    done               BOOLEAN NOT NULL DEFAULT FALSE,
    last_read_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, subject_key)
);
CREATE INDEX notification_threads_user ON notification_threads (user_id, updated_at DESC);

-- Explicit (un)subscriptions to a subject, per user.
CREATE TABLE notification_subscriptions (
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    subject_key TEXT NOT NULL,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    subscribed  BOOLEAN NOT NULL DEFAULT TRUE,
    ignored     BOOLEAN NOT NULL DEFAULT FALSE,
    reason      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, subject_key)
);

-- Repository invitations ------------------------------------------------------------------------------
CREATE TABLE repo_invitations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    invitee_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    inviter_id  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    permission  TEXT NOT NULL DEFAULT 'push',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, invitee_id)
);
CREATE INDEX repo_invitations_invitee ON repo_invitations (invitee_id);

-- Dependency graph snapshots (POST /dependency-graph/snapshots) ---------------------------------------
CREATE TABLE dependency_snapshots (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    sha        TEXT NOT NULL,
    ref        TEXT NOT NULL,
    job_correlator TEXT NOT NULL,
    detector   JSONB NOT NULL,
    job        JSONB NOT NULL,
    metadata   JSONB NOT NULL DEFAULT '{}',
    manifests  JSONB NOT NULL DEFAULT '{}',
    scanned    TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX dependency_snapshots_repo ON dependency_snapshots (repo_id, sha, id DESC);

-- Environments that existed implicitly (deployments) before this migration.
INSERT INTO environments (repo_id, name, created_at)
SELECT repo_id, environment, min(created_at) FROM deployments GROUP BY repo_id, environment
ON CONFLICT (repo_id, lower(name)) DO NOTHING;
