-- Advanced security (advsec area): advisory database, Dependabot alerts and secrets, secret
-- scanning, code scanning (SARIF), code security configurations, dismissal/bypass requests.

-- Per-repository alert number sequences (one per alert kind).
CREATE TABLE advsec_counters (
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    kind    TEXT NOT NULL,
    next    BIGINT NOT NULL DEFAULT 1,
    PRIMARY KEY (repo_id, kind)
);

-- ---------------------------------------------------------------------------------------------
-- Advisory database (GitHub Advisory Database, imported from OSV records)

CREATE TABLE advisories (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ghsa_id              TEXT NOT NULL UNIQUE,
    cve_id               TEXT,
    kind                 TEXT NOT NULL DEFAULT 'reviewed',   -- reviewed | unreviewed | malware
    summary              TEXT NOT NULL DEFAULT '',
    description          TEXT,
    severity             TEXT NOT NULL DEFAULT 'unknown',    -- critical | high | medium | low | unknown
    cvss_v3_vector       TEXT,
    cvss_v3_score        DOUBLE PRECISION,
    cvss_v4_vector       TEXT,
    cvss_v4_score        DOUBLE PRECISION,
    cwes                 JSONB NOT NULL DEFAULT '[]',        -- [{cwe_id, name}]
    identifiers          JSONB NOT NULL DEFAULT '[]',        -- [{type, value}]
    refs                 JSONB NOT NULL DEFAULT '[]',        -- [url]
    source_code_location TEXT,
    credits              JSONB NOT NULL DEFAULT '[]',        -- [{login, type}]
    epss                 JSONB,
    published_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    github_reviewed_at   TIMESTAMPTZ,
    nvd_published_at     TIMESTAMPTZ,
    withdrawn_at         TIMESTAMPTZ,
    imported_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX advisories_cve ON advisories (cve_id);
CREATE INDEX advisories_published ON advisories (published_at DESC, id DESC);

CREATE TABLE advisory_vulnerabilities (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advisory_id              BIGINT NOT NULL REFERENCES advisories(id) ON DELETE CASCADE,
    ecosystem                TEXT NOT NULL,       -- GitHub names: npm, pip, rust, go, rubygems, maven, ...
    package                  TEXT NOT NULL,
    vulnerable_version_range TEXT NOT NULL DEFAULT '',
    first_patched_version    TEXT,
    vulnerable_functions     TEXT[] NOT NULL DEFAULT '{}',
    ranges                   JSONB NOT NULL DEFAULT '[]',  -- OSV range events [[{introduced|fixed|last_affected: v}]]
    versions                 TEXT[] NOT NULL DEFAULT '{}'  -- explicitly listed affected versions
);
CREATE INDEX advisory_vulns_pkg ON advisory_vulnerabilities (ecosystem, lower(package));
CREATE INDEX advisory_vulns_adv ON advisory_vulnerabilities (advisory_id);

-- ---------------------------------------------------------------------------------------------
-- Dependabot

CREATE TABLE dependabot_alerts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id           BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number            BIGINT NOT NULL,
    advisory_id       BIGINT NOT NULL REFERENCES advisories(id) ON DELETE CASCADE,
    vulnerability_id  BIGINT NOT NULL REFERENCES advisory_vulnerabilities(id) ON DELETE CASCADE,
    ecosystem         TEXT NOT NULL,
    package           TEXT NOT NULL,
    manifest_path     TEXT NOT NULL,
    scope             TEXT,
    version           TEXT NOT NULL DEFAULT '',
    state             TEXT NOT NULL DEFAULT 'open',   -- open | dismissed | fixed | auto_dismissed
    dismissed_at      TIMESTAMPTZ,
    dismissed_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    dismissed_reason  TEXT,
    dismissed_comment TEXT,
    fixed_at          TIMESTAMPTZ,
    auto_dismissed_at TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, number),
    UNIQUE (repo_id, advisory_id, ecosystem, package, manifest_path)
);
CREATE INDEX dependabot_alerts_state ON dependabot_alerts (repo_id, state);

CREATE TABLE dependabot_alert_assignees (
    alert_id BIGINT NOT NULL REFERENCES dependabot_alerts(id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (alert_id, user_id)
);

-- Dependabot secrets (sealed boxes, like Actions secrets; keys in actions_public_keys with
-- owner_kind 'dependabot-repo' / 'dependabot-org').
CREATE TABLE dependabot_secrets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id         BIGINT REFERENCES repositories(id) ON DELETE CASCADE,
    org_id          BIGINT REFERENCES users(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    encrypted_value TEXT NOT NULL,
    key_id          TEXT NOT NULL,
    visibility      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((repo_id IS NULL) <> (org_id IS NULL))
);
CREATE UNIQUE INDEX dependabot_secrets_owner ON dependabot_secrets (COALESCE(repo_id, 0), COALESCE(org_id, 0), name);
CREATE TABLE dependabot_secret_repos (
    secret_id BIGINT NOT NULL REFERENCES dependabot_secrets(id) ON DELETE CASCADE,
    repo_id   BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    PRIMARY KEY (secret_id, repo_id)
);

-- Repositories Dependabot may read when updating an org's private dependencies.
CREATE TABLE dependabot_repository_access (
    org_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    PRIMARY KEY (org_id, repo_id)
);
CREATE TABLE dependabot_org_settings (
    org_id        BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    default_level TEXT
);

-- ---------------------------------------------------------------------------------------------
-- Secret scanning

CREATE TABLE secret_scanning_alerts (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id                    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number                     BIGINT NOT NULL,
    secret_type                TEXT NOT NULL,
    secret                     TEXT NOT NULL,
    secret_hash                TEXT NOT NULL,
    state                      TEXT NOT NULL DEFAULT 'open',   -- open | resolved
    resolution                 TEXT,
    resolution_comment         TEXT,
    resolved_at                TIMESTAMPTZ,
    resolved_by                BIGINT REFERENCES users(id) ON DELETE SET NULL,
    validity                   TEXT NOT NULL DEFAULT 'unknown',
    push_protection_bypassed    BOOLEAN NOT NULL DEFAULT false,
    push_protection_bypassed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    push_protection_bypassed_at TIMESTAMPTZ,
    bypass_request_id          BIGINT,
    assigned_to                BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, number),
    UNIQUE (repo_id, secret_type, secret_hash)
);
CREATE INDEX secret_scanning_alerts_state ON secret_scanning_alerts (repo_id, state);

CREATE TABLE secret_scanning_locations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id     BIGINT NOT NULL REFERENCES secret_scanning_alerts(id) ON DELETE CASCADE,
    commit_sha   TEXT NOT NULL,
    blob_sha     TEXT NOT NULL,
    path         TEXT NOT NULL,
    start_line   INT NOT NULL,
    end_line     INT NOT NULL,
    start_column INT NOT NULL,
    end_column   INT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (alert_id, commit_sha, path, start_line, start_column)
);

-- Scan history (incremental scans per push, backfills when enabled).
CREATE TABLE secret_scanning_scans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id      BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    kind         TEXT NOT NULL,   -- incremental | backfill | pattern_update
    status       TEXT NOT NULL DEFAULT 'pending',
    started_at   TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX secret_scanning_scans_repo ON secret_scanning_scans (repo_id, id DESC);

-- Secrets a push was blocked for (push protection), keyed by the placeholder id the client is
-- shown; bypasses allow that secret into the repository for a while.
CREATE TABLE secret_scanning_push_blocks (
    repo_id        BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    placeholder_id TEXT NOT NULL,
    token_type     TEXT NOT NULL,
    path           TEXT NOT NULL DEFAULT '',
    branch         TEXT NOT NULL DEFAULT '',
    actor_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (repo_id, placeholder_id)
);
CREATE TABLE secret_scanning_push_bypasses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id        BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    placeholder_id TEXT NOT NULL,
    token_type     TEXT NOT NULL,
    reason         TEXT NOT NULL,
    actor_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
    request_id     BIGINT,
    expire_at      TIMESTAMPTZ NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, placeholder_id)
);

-- Pattern configuration (push protection per token type) for orgs (owner_id) and the
-- enterprise (owner_id 0).
CREATE TABLE secret_scanning_pattern_settings (
    owner_kind TEXT NOT NULL,   -- org | enterprise
    owner_id   BIGINT NOT NULL,
    token_type TEXT NOT NULL,
    setting    TEXT NOT NULL,   -- not-set | disabled | enabled
    PRIMARY KEY (owner_kind, owner_id, token_type)
);
CREATE TABLE secret_scanning_pattern_versions (
    owner_kind TEXT NOT NULL,
    owner_id   BIGINT NOT NULL,
    version    TEXT NOT NULL,
    PRIMARY KEY (owner_kind, owner_id)
);

-- ---------------------------------------------------------------------------------------------
-- Delegated bypass / alert dismissal requests (secret scanning, code scanning, Dependabot)

CREATE TABLE advsec_requests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id           BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number            BIGINT NOT NULL,
    kind              TEXT NOT NULL,   -- secret_scanning_bypass | secret_scanning_dismissal | code_scanning_dismissal | dependabot_dismissal
    alert_number      BIGINT,
    requester_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status            TEXT NOT NULL DEFAULT 'open',
    reason            TEXT,
    requester_comment TEXT,
    data              JSONB NOT NULL DEFAULT '{}',
    resource_identifier TEXT NOT NULL DEFAULT '',
    expires_at        TIMESTAMPTZ NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, kind, number)
);
CREATE INDEX advsec_requests_alert ON advsec_requests (repo_id, kind, alert_number);
CREATE TABLE advsec_request_responses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT NOT NULL REFERENCES advsec_requests(id) ON DELETE CASCADE,
    reviewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status      TEXT NOT NULL,   -- approved | denied | dismissed
    message     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------------------------
-- Code scanning

CREATE TABLE code_scanning_sarifs (
    id               TEXT PRIMARY KEY,   -- uuid
    repo_id          BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    commit_sha       TEXT NOT NULL,
    ref              TEXT NOT NULL,
    tool_name        TEXT,
    checkout_uri     TEXT,
    started_at       TIMESTAMPTZ,
    storage_key      TEXT NOT NULL,
    status           TEXT NOT NULL DEFAULT 'pending',   -- pending | complete | failed
    errors           JSONB,
    uploader_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE code_scanning_analyses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    sarif_id      TEXT NOT NULL REFERENCES code_scanning_sarifs(id) ON DELETE CASCADE,
    run_index     INT NOT NULL,
    ref           TEXT NOT NULL,
    commit_sha    TEXT NOT NULL,
    analysis_key  TEXT NOT NULL,
    environment   TEXT NOT NULL DEFAULT '{}',
    category      TEXT NOT NULL DEFAULT '',
    tool_name     TEXT NOT NULL,
    tool_version  TEXT,
    tool_guid     TEXT,
    results_count INT NOT NULL DEFAULT 0,
    rules_count   INT NOT NULL DEFAULT 0,
    error         TEXT NOT NULL DEFAULT '',
    warning       TEXT NOT NULL DEFAULT '',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX code_scanning_analyses_set ON code_scanning_analyses (repo_id, ref, tool_name, category, id DESC);

CREATE TABLE code_scanning_alerts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id           BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number            BIGINT NOT NULL,
    tool_name         TEXT NOT NULL,
    tool_version      TEXT,
    tool_guid         TEXT,
    rule_id           TEXT NOT NULL,
    rule              JSONB NOT NULL DEFAULT '{}',   -- {name, severity, security_severity_level, description, full_description, tags, help, help_uri}
    fingerprint       TEXT NOT NULL,
    state             TEXT NOT NULL DEFAULT 'open',  -- open | dismissed | fixed
    fixed_at          TIMESTAMPTZ,
    dismissed_at      TIMESTAMPTZ,
    dismissed_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    dismissed_reason  TEXT,
    dismissed_comment TEXT,
    dismissal_approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, number),
    UNIQUE (repo_id, tool_name, rule_id, fingerprint)
);
CREATE TABLE code_scanning_alert_assignees (
    alert_id BIGINT NOT NULL REFERENCES code_scanning_alerts(id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (alert_id, user_id)
);

-- One row per alert found by an analysis.
CREATE TABLE code_scanning_results (
    analysis_id    BIGINT NOT NULL REFERENCES code_scanning_analyses(id) ON DELETE CASCADE,
    alert_id       BIGINT NOT NULL REFERENCES code_scanning_alerts(id) ON DELETE CASCADE,
    message        TEXT NOT NULL DEFAULT '',
    path           TEXT NOT NULL DEFAULT '',
    start_line     INT,
    end_line       INT,
    start_column   INT,
    end_column     INT,
    classifications TEXT[] NOT NULL DEFAULT '{}',
    PRIMARY KEY (analysis_id, alert_id)
);
CREATE INDEX code_scanning_results_alert ON code_scanning_results (alert_id);

CREATE TABLE code_scanning_default_setup (
    repo_id      BIGINT PRIMARY KEY REFERENCES repositories(id) ON DELETE CASCADE,
    state        TEXT NOT NULL DEFAULT 'not-configured',
    languages    TEXT[] NOT NULL DEFAULT '{}',
    runner_type  TEXT,
    runner_label TEXT,
    query_suite  TEXT NOT NULL DEFAULT 'default',
    threat_model TEXT NOT NULL DEFAULT 'remote',
    updated_at   TIMESTAMPTZ
);

-- ---------------------------------------------------------------------------------------------
-- Code security configurations

CREATE TABLE code_security_configurations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    target_type TEXT NOT NULL,          -- global | organization | enterprise
    owner_id    BIGINT NOT NULL DEFAULT 0,   -- org id; 0 for global / enterprise
    name        TEXT NOT NULL,
    description TEXT,
    settings    JSONB NOT NULL DEFAULT '{}',
    enforcement TEXT NOT NULL DEFAULT 'enforced',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX code_security_configurations_name ON code_security_configurations (target_type, owner_id, lower(name));

CREATE TABLE code_security_configuration_repos (
    repo_id          BIGINT PRIMARY KEY REFERENCES repositories(id) ON DELETE CASCADE,
    configuration_id BIGINT NOT NULL REFERENCES code_security_configurations(id) ON DELETE CASCADE,
    status           TEXT NOT NULL DEFAULT 'attached',
    attached_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Defaults for new repositories, per organization (scope_id = org id) or the enterprise (0).
CREATE TABLE code_security_defaults (
    scope_kind            TEXT NOT NULL,   -- org | enterprise
    scope_id              BIGINT NOT NULL,
    configuration_id      BIGINT NOT NULL REFERENCES code_security_configurations(id) ON DELETE CASCADE,
    default_for_new_repos TEXT NOT NULL,   -- all | public | private_and_internal
    PRIMARY KEY (scope_kind, scope_id, configuration_id)
);

CREATE INDEX code_security_configuration_repos_cfg ON code_security_configuration_repos (configuration_id);

