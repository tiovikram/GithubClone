-- gh compatibility (area ghcompat): OAuth 2.0 device authorization grant, the flow behind
-- `gh auth login --web` / `gh auth refresh`. Codes are short-lived; the device code is stored
-- hashed, the user code is what the person types on the approval page.
CREATE TABLE oauth_device_codes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code_hash TEXT NOT NULL UNIQUE,
    user_code        TEXT NOT NULL UNIQUE,
    client_id        TEXT NOT NULL,
    scopes           TEXT NOT NULL DEFAULT '',
    user_id          BIGINT REFERENCES users(id) ON DELETE CASCADE,
    status           TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'denied')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at       TIMESTAMPTZ NOT NULL
);
CREATE INDEX oauth_device_codes_expires ON oauth_device_codes (expires_at);
