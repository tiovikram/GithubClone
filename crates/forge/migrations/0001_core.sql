-- forge core schema. Shapes follow GitHub's data model; ids are integers like GitHub's.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login           TEXT NOT NULL,
    kind            TEXT NOT NULL DEFAULT 'User' CHECK (kind IN ('User', 'Organization', 'Bot')),
    name            TEXT,
    email           TEXT,
    password_hash   TEXT,
    bio             TEXT,
    company         TEXT,
    location        TEXT,
    blog            TEXT NOT NULL DEFAULT '',
    twitter_username TEXT,
    site_admin      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_login_lower ON users (lower(login));

CREATE TABLE org_members (
    org_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role     TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('member', 'admin')),
    PRIMARY KEY (org_id, user_id)
);

CREATE TABLE tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    token_hash  TEXT NOT NULL UNIQUE,
    token_last_eight TEXT NOT NULL,
    scopes      TEXT[] NOT NULL DEFAULT ARRAY['repo','read:org','gist','workflow','admin:org','user','delete_repo'],
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    expires_at  TIMESTAMPTZ
);

CREATE TABLE sessions (
    id_hash     TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE repositories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    description     TEXT,
    homepage        TEXT,
    private         BOOLEAN NOT NULL DEFAULT FALSE,
    visibility      TEXT NOT NULL DEFAULT 'public',
    default_branch  TEXT NOT NULL DEFAULT 'main',
    fork_parent_id  BIGINT REFERENCES repositories(id) ON DELETE SET NULL,
    archived        BOOLEAN NOT NULL DEFAULT FALSE,
    is_template     BOOLEAN NOT NULL DEFAULT FALSE,
    has_issues      BOOLEAN NOT NULL DEFAULT TRUE,
    has_projects    BOOLEAN NOT NULL DEFAULT TRUE,
    has_wiki        BOOLEAN NOT NULL DEFAULT TRUE,
    has_discussions BOOLEAN NOT NULL DEFAULT FALSE,
    allow_merge_commit BOOLEAN NOT NULL DEFAULT TRUE,
    allow_squash_merge BOOLEAN NOT NULL DEFAULT TRUE,
    allow_rebase_merge BOOLEAN NOT NULL DEFAULT TRUE,
    allow_auto_merge   BOOLEAN NOT NULL DEFAULT FALSE,
    delete_branch_on_merge BOOLEAN NOT NULL DEFAULT FALSE,
    topics          TEXT[] NOT NULL DEFAULT '{}',
    language        TEXT,
    size_kb         BIGINT NOT NULL DEFAULT 0,
    next_number     BIGINT NOT NULL DEFAULT 1,
    stargazers_count BIGINT NOT NULL DEFAULT 0,
    forks_count     BIGINT NOT NULL DEFAULT 0,
    open_issues_count BIGINT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    pushed_at       TIMESTAMPTZ
);
CREATE UNIQUE INDEX repositories_owner_name ON repositories (owner_id, lower(name));

CREATE TABLE repo_collaborators (
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    permission TEXT NOT NULL DEFAULT 'push' CHECK (permission IN ('pull','triage','push','maintain','admin')),
    PRIMARY KEY (repo_id, user_id)
);

-- Git storage manifest: object storage holds packs; this row is the atomic commit point.
CREATE TABLE repo_storage (
    repo_id    BIGINT PRIMARY KEY REFERENCES repositories(id) ON DELETE CASCADE,
    version    BIGINT NOT NULL DEFAULT 0,
    head       TEXT NOT NULL DEFAULT 'refs/heads/main',
    refs       TEXT NOT NULL DEFAULT '',      -- packed-refs body: "<sha> <refname>\n"...
    packs      TEXT[] NOT NULL DEFAULT '{}',  -- pack basenames, e.g. pack-<sha>
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Deleted repos leave packs behind; gc removes them.
CREATE TABLE storage_trash (
    prefix     TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE milestones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number      BIGINT NOT NULL,
    title       TEXT NOT NULL,
    description TEXT,
    state       TEXT NOT NULL DEFAULT 'open' CHECK (state IN ('open','closed')),
    due_on      TIMESTAMPTZ,
    creator_id  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at   TIMESTAMPTZ,
    UNIQUE (repo_id, number)
);

CREATE TABLE labels (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    color       TEXT NOT NULL DEFAULT 'ededed',
    description TEXT,
    is_default  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX labels_repo_name ON labels (repo_id, lower(name));

-- Issues and pull requests share this table and the per-repo number sequence.
CREATE TABLE issues (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number        BIGINT NOT NULL,
    is_pull       BOOLEAN NOT NULL DEFAULT FALSE,
    title         TEXT NOT NULL,
    body          TEXT,
    state         TEXT NOT NULL DEFAULT 'open' CHECK (state IN ('open','closed')),
    state_reason  TEXT,
    user_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
    milestone_id  BIGINT REFERENCES milestones(id) ON DELETE SET NULL,
    locked        BOOLEAN NOT NULL DEFAULT FALSE,
    active_lock_reason TEXT,
    comments_count BIGINT NOT NULL DEFAULT 0,
    closed_by_id  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at     TIMESTAMPTZ,
    UNIQUE (repo_id, number)
);
CREATE INDEX issues_repo_state ON issues (repo_id, is_pull, state, number DESC);
CREATE INDEX issues_user ON issues (user_id);

CREATE TABLE issue_labels (
    issue_id BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    label_id BIGINT NOT NULL REFERENCES labels(id) ON DELETE CASCADE,
    PRIMARY KEY (issue_id, label_id)
);

CREATE TABLE issue_assignees (
    issue_id BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (issue_id, user_id)
);

CREATE TABLE issue_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    body       TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX issue_comments_issue ON issue_comments (issue_id, id);
CREATE INDEX issue_comments_repo ON issue_comments (repo_id, id);

-- Timeline / issue events (closed, reopened, labeled, merged, referenced, head_ref_deleted ...)
CREATE TABLE issue_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    actor_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    event      TEXT NOT NULL,
    commit_id  TEXT,
    data       JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX issue_events_issue ON issue_events (issue_id, id);

CREATE TABLE pull_requests (
    issue_id        BIGINT PRIMARY KEY REFERENCES issues(id) ON DELETE CASCADE,
    repo_id         BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    head_repo_id    BIGINT REFERENCES repositories(id) ON DELETE SET NULL,
    head_ref        TEXT NOT NULL,
    head_sha        TEXT NOT NULL,
    base_ref        TEXT NOT NULL,
    base_sha        TEXT NOT NULL,
    merge_base_sha  TEXT,
    draft           BOOLEAN NOT NULL DEFAULT FALSE,
    merged          BOOLEAN NOT NULL DEFAULT FALSE,
    merged_at       TIMESTAMPTZ,
    merged_by_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    merge_commit_sha TEXT,
    maintainer_can_modify BOOLEAN NOT NULL DEFAULT FALSE,
    additions       BIGINT NOT NULL DEFAULT 0,
    deletions       BIGINT NOT NULL DEFAULT 0,
    changed_files   BIGINT NOT NULL DEFAULT 0,
    commits_count   BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX pull_requests_head ON pull_requests (head_repo_id, head_ref);
CREATE INDEX pull_requests_base ON pull_requests (repo_id, base_ref);

CREATE TABLE pull_reviews (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id     BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    user_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    body         TEXT NOT NULL DEFAULT '',
    state        TEXT NOT NULL CHECK (state IN ('PENDING','COMMENTED','APPROVED','CHANGES_REQUESTED','DISMISSED')),
    commit_id    TEXT,
    submitted_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX pull_reviews_issue ON pull_reviews (issue_id, id);

CREATE TABLE review_comments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id      BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    review_id     BIGINT REFERENCES pull_reviews(id) ON DELETE CASCADE,
    in_reply_to_id BIGINT REFERENCES review_comments(id) ON DELETE SET NULL,
    user_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
    body          TEXT NOT NULL,
    path          TEXT NOT NULL,
    commit_id     TEXT NOT NULL,
    original_commit_id TEXT NOT NULL,
    diff_hunk     TEXT NOT NULL DEFAULT '',
    line          BIGINT,
    original_line BIGINT,
    start_line    BIGINT,
    side          TEXT NOT NULL DEFAULT 'RIGHT',
    start_side    TEXT,
    position      BIGINT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX review_comments_issue ON review_comments (issue_id, id);

CREATE TABLE reactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type TEXT NOT NULL,   -- issue | issue_comment | review_comment | release
    subject_id  BIGINT NOT NULL,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content     TEXT NOT NULL CHECK (content IN ('+1','-1','laugh','confused','heart','hooray','rocket','eyes')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (subject_type, subject_id, user_id, content)
);

CREATE TABLE releases (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    tag_name      TEXT NOT NULL,
    target_commitish TEXT NOT NULL,
    name          TEXT,
    body          TEXT,
    draft         BOOLEAN NOT NULL DEFAULT FALSE,
    prerelease    BOOLEAN NOT NULL DEFAULT FALSE,
    make_latest   TEXT NOT NULL DEFAULT 'true',
    author_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at  TIMESTAMPTZ
);
CREATE UNIQUE INDEX releases_repo_tag ON releases (repo_id, tag_name);

CREATE TABLE release_assets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id    BIGINT NOT NULL REFERENCES releases(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    label         TEXT,
    content_type  TEXT NOT NULL,
    size          BIGINT NOT NULL,
    storage_key   TEXT NOT NULL,
    download_count BIGINT NOT NULL DEFAULT 0,
    uploader_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (release_id, name)
);

CREATE TABLE stars (
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, repo_id)
);

CREATE TABLE watches (
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, repo_id)
);

CREATE TABLE commit_statuses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    sha         TEXT NOT NULL,
    state       TEXT NOT NULL CHECK (state IN ('error','failure','pending','success')),
    context     TEXT NOT NULL DEFAULT 'default',
    description TEXT,
    target_url  TEXT,
    creator_id  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX commit_statuses_sha ON commit_statuses (repo_id, sha, id DESC);

CREATE TABLE webhooks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT REFERENCES repositories(id) ON DELETE CASCADE,
    org_id      BIGINT REFERENCES users(id) ON DELETE CASCADE,
    config      JSONB NOT NULL,
    events      TEXT[] NOT NULL DEFAULT ARRAY['push'],
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE ssh_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    key         TEXT NOT NULL,
    fingerprint TEXT NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
