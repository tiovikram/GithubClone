-- gh compatibility (area `ghcompat`): autolink references, repository/organization rulesets,
-- SSH signing keys.

CREATE TABLE autolinks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id         BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    key_prefix      TEXT NOT NULL,
    url_template    TEXT NOT NULL,
    is_alphanumeric BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX autolinks_repo_prefix ON autolinks (repo_id, lower(key_prefix));

-- A ruleset belongs to exactly one repository or one organization.
CREATE TABLE rulesets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT REFERENCES repositories(id) ON DELETE CASCADE,
    org_id        BIGINT REFERENCES users(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    target        TEXT NOT NULL DEFAULT 'branch' CHECK (target IN ('branch', 'tag', 'push')),
    enforcement   TEXT NOT NULL CHECK (enforcement IN ('disabled', 'active', 'evaluate')),
    conditions    JSONB,
    rules         JSONB NOT NULL DEFAULT '[]',
    bypass_actors JSONB NOT NULL DEFAULT '[]',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((repo_id IS NULL) <> (org_id IS NULL))
);
CREATE INDEX rulesets_repo_idx ON rulesets (repo_id, id);
CREATE INDEX rulesets_org_idx ON rulesets (org_id, id);

-- SSH keys registered for commit signing (separate namespace from authentication keys,
-- as on GitHub: the same key may be both).
CREATE TABLE ssh_signing_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    key         TEXT NOT NULL,
    fingerprint TEXT NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ssh_signing_keys_user_idx ON ssh_signing_keys (user_id, id);
