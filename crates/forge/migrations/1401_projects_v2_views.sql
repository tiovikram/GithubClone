-- Projects (v2) views (area packages: the REST projects API). Every project also has an
-- implicit default table view number 1 ("View 1") showing all items.
CREATE TABLE projects_v2_views (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        BIGINT NOT NULL REFERENCES projects_v2(id) ON DELETE CASCADE,
    number            BIGINT NOT NULL,
    name              TEXT NOT NULL,
    layout            TEXT NOT NULL CHECK (layout IN ('table', 'board', 'roadmap')),
    filter            TEXT,
    visible_fields    JSONB NOT NULL DEFAULT '[]',
    sort_by           JSONB NOT NULL DEFAULT '[]',
    group_by          JSONB NOT NULL DEFAULT '[]',
    vertical_group_by JSONB NOT NULL DEFAULT '[]',
    creator_id        BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (project_id, number)
);

-- When an item was archived (the REST `archived_at`).
ALTER TABLE projects_v2_items ADD COLUMN archived_at TIMESTAMPTZ;
UPDATE projects_v2_items SET archived_at = updated_at WHERE archived;

CREATE FUNCTION projects_v2_items_archived_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.archived AND (TG_OP = 'INSERT' OR NOT OLD.archived) THEN
        NEW.archived_at := COALESCE(NEW.archived_at, now());
    ELSIF NOT NEW.archived THEN
        NEW.archived_at := NULL;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER projects_v2_items_archived_at BEFORE INSERT OR UPDATE OF archived ON projects_v2_items
    FOR EACH ROW EXECUTE FUNCTION projects_v2_items_archived_at();
