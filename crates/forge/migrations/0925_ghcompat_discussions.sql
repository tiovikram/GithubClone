-- gh compatibility (area ghcompat): repository discussions (`gh discussion ...`, GraphQL
-- Repository.discussions / createDiscussion / addDiscussionComment ...). Discussions share the
-- repository's issue/PR number sequence, like GitHub.

CREATE TABLE discussion_categories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    slug          TEXT NOT NULL,
    emoji         TEXT NOT NULL DEFAULT ':speech_balloon:',
    description   TEXT NOT NULL DEFAULT '',
    is_answerable BOOLEAN NOT NULL DEFAULT FALSE,
    position      INT NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, slug)
);

CREATE TABLE discussions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id            BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number             BIGINT NOT NULL,
    category_id        BIGINT NOT NULL REFERENCES discussion_categories(id),
    user_id            BIGINT REFERENCES users(id) ON DELETE SET NULL,
    title              TEXT NOT NULL,
    body               TEXT NOT NULL DEFAULT '',
    closed             BOOLEAN NOT NULL DEFAULT FALSE,
    state_reason       TEXT CHECK (state_reason IN ('resolved', 'outdated', 'duplicate', 'reopened')),
    locked             BOOLEAN NOT NULL DEFAULT FALSE,
    answer_comment_id  BIGINT,
    answer_chosen_at   TIMESTAMPTZ,
    answer_chosen_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at          TIMESTAMPTZ,
    UNIQUE (repo_id, number)
);
CREATE INDEX discussions_repo_updated ON discussions (repo_id, updated_at DESC);

CREATE TABLE discussion_labels (
    discussion_id BIGINT NOT NULL REFERENCES discussions(id) ON DELETE CASCADE,
    label_id      BIGINT NOT NULL REFERENCES labels(id) ON DELETE CASCADE,
    PRIMARY KEY (discussion_id, label_id)
);

-- Top-level comments have parent_id NULL; replies point at their top-level comment.
CREATE TABLE discussion_comments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id BIGINT NOT NULL REFERENCES discussions(id) ON DELETE CASCADE,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    parent_id     BIGINT REFERENCES discussion_comments(id) ON DELETE CASCADE,
    user_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
    body          TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX discussion_comments_discussion ON discussion_comments (discussion_id, parent_id, id);
