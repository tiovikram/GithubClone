-- Checks API: check suites (one per repo, head_sha and app), check runs and their annotations.
-- forge has no GitHub Apps; every suite/run belongs to the built-in "forge" app (app_id 1).
CREATE TABLE check_suites (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    app_id        BIGINT NOT NULL DEFAULT 1,
    head_sha      TEXT NOT NULL,
    head_branch   TEXT,
    -- status/conclusion of a suite without runs; with runs they are derived from the runs
    status        TEXT NOT NULL DEFAULT 'queued',
    conclusion    TEXT,
    creator_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    rerequested_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, head_sha, app_id)
);

CREATE TABLE check_runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id        BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    suite_id       BIGINT NOT NULL REFERENCES check_suites(id) ON DELETE CASCADE,
    head_sha       TEXT NOT NULL,
    name           TEXT NOT NULL,
    external_id    TEXT,
    details_url    TEXT,
    status         TEXT NOT NULL DEFAULT 'queued',
    conclusion     TEXT,
    started_at     TIMESTAMPTZ,
    completed_at   TIMESTAMPTZ,
    output_title   TEXT,
    output_summary TEXT,
    output_text    TEXT,
    output_images  JSONB NOT NULL DEFAULT '[]',
    actions        JSONB NOT NULL DEFAULT '[]',
    creator_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX check_runs_repo_sha ON check_runs (repo_id, head_sha);
CREATE INDEX check_runs_suite ON check_runs (suite_id);

CREATE TABLE check_annotations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_run_id     BIGINT NOT NULL REFERENCES check_runs(id) ON DELETE CASCADE,
    path             TEXT NOT NULL,
    start_line       INT NOT NULL,
    end_line         INT NOT NULL,
    start_column     INT,
    end_column       INT,
    annotation_level TEXT NOT NULL,
    title            TEXT,
    message          TEXT NOT NULL,
    raw_details      TEXT
);
CREATE INDEX check_annotations_run ON check_annotations (check_run_id, id);

-- Reactions on pull request review comments (polymorphic, no FK): clean up on delete, including
-- the cascade from a deleted repository.
CREATE TRIGGER review_comments_reactions_cleanup AFTER DELETE ON review_comments
    FOR EACH ROW EXECUTE FUNCTION forge_reactions_cleanup('review_comment');
