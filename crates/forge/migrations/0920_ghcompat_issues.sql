-- gh compatibility (area ghcompat): pinned issues (`gh issue pin/unpin`, Issue.isPinned) and
-- branches linked to issues (`gh issue develop`, Issue.linkedBranches).

CREATE TABLE pinned_issues (
    issue_id   BIGINT PRIMARY KEY REFERENCES issues(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    pinned_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX pinned_issues_repo ON pinned_issues (repo_id, created_at);

-- A link survives only while the branch exists (readers filter on the current refs).
CREATE TABLE linked_branches (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    ref_name   TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (issue_id, repo_id, ref_name)
);
CREATE INDEX linked_branches_issue ON linked_branches (issue_id, id);
