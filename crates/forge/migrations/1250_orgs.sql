CREATE TABLE org_role_users (
    org_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES org_roles(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (org_id, role_id, user_id)
);
CREATE INDEX org_role_users_user ON org_role_users (user_id);
CREATE TABLE org_role_teams (
    org_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES org_roles(id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    PRIMARY KEY (org_id, role_id, team_id)
);

-- Organization audit log (real events recorded by forge's org/team/role/registry services).
CREATE TABLE org_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    action      TEXT NOT NULL,
    actor_id    BIGINT,
    actor       TEXT,
    user_login  TEXT,
    repo        TEXT,
    team        TEXT,
    data        JSONB NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX org_audit_log_org ON org_audit_log (org_id, id DESC);

-- Custom property definitions (org level) and their values on repositories.
CREATE TABLE custom_property_definitions (
    org_id                  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    property_name           TEXT NOT NULL,
    value_type              TEXT NOT NULL CHECK (value_type IN ('string', 'single_select', 'multi_select', 'true_false', 'url')),
    required                BOOLEAN NOT NULL DEFAULT FALSE,
    default_value           JSONB,
    description             TEXT,
    allowed_values          TEXT[],
    values_editable_by      TEXT NOT NULL DEFAULT 'org_actors',
    require_explicit_values BOOLEAN NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, property_name)
);
CREATE TABLE repo_custom_property_values (
    repo_id       BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    property_name TEXT NOT NULL,
    value         JSONB NOT NULL,
    PRIMARY KEY (repo_id, property_name)
);
-- Custom property values set on the organization itself (definitions live at enterprise level).
CREATE TABLE org_custom_property_values (
    org_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    property_name TEXT NOT NULL,
    value         JSONB NOT NULL,
    PRIMARY KEY (org_id, property_name)
);

-- Private registry configurations. The secret arrives as a libsodium sealed box against the
-- org's registry public key; forge keeps the X25519 private key to verify (open) it.
CREATE TABLE org_registry_keys (
    org_id      BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    key_id      TEXT NOT NULL,
    public_key  TEXT NOT NULL,
    private_key TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE org_private_registries (
    org_id                 BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name                   TEXT NOT NULL,
    registry_type          TEXT NOT NULL,
    auth_type              TEXT,
    url                    TEXT NOT NULL,
    username               TEXT,
    replaces_base          BOOLEAN NOT NULL DEFAULT FALSE,
    visibility             TEXT NOT NULL CHECK (visibility IN ('all', 'private', 'selected')),
    selected_repository_ids BIGINT[] NOT NULL DEFAULT '{}',
    oidc                   JSONB NOT NULL DEFAULT '{}',
    encrypted_value        TEXT,
    key_id                 TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, name)
);

-- Repositories selected for immutable releases when org_settings.immutable_releases = 'selected'.
CREATE TABLE org_immutable_release_repos (
    org_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    PRIMARY KEY (org_id, repo_id)
);

-- Security products enabled per repository by the org-wide enable/disable endpoint.
CREATE TABLE repo_security_products (
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    product    TEXT NOT NULL,
    enabled    BOOLEAN NOT NULL,
    options    JSONB NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (repo_id, product)
);

-- External identity-provider groups (populated by SCIM provisioning) and their team links.
CREATE TABLE external_groups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     BIGINT REFERENCES users(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE external_group_members (
    group_id BIGINT NOT NULL REFERENCES external_groups(id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, user_id)
);
CREATE TABLE team_external_groups (
    team_id  BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES external_groups(id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, group_id)
);

-- Ruleset versions (one per create/update) for the ruleset history endpoints.
CREATE TABLE ruleset_versions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruleset_id BIGINT NOT NULL REFERENCES rulesets(id) ON DELETE CASCADE,
    actor_id   BIGINT,
    state      JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ruleset_versions_ruleset ON ruleset_versions (ruleset_id, id DESC);
