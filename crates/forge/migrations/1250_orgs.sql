-- Organizations build-out (area "orgs", range 1250-1299): org settings (incl. the default
-- repository permission that org members get), public membership, team repository access,
-- custom repository roles, organization roles, audit log, custom properties, private
-- registries, announcement banners, immutable-release settings, external IdP groups and
-- ruleset history.

-- Settings that are not columns of `users`. A missing row means GitHub's defaults.
CREATE TABLE org_settings (
    org_id                                    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    billing_email                             TEXT,
    default_repository_permission             TEXT NOT NULL DEFAULT 'read'
        CHECK (default_repository_permission IN ('read', 'write', 'admin', 'none')),
    has_organization_projects                 BOOLEAN NOT NULL DEFAULT TRUE,
    has_repository_projects                   BOOLEAN NOT NULL DEFAULT TRUE,
    members_can_create_repositories           BOOLEAN NOT NULL DEFAULT TRUE,
    members_can_create_public_repositories    BOOLEAN NOT NULL DEFAULT TRUE,
    members_can_create_private_repositories   BOOLEAN NOT NULL DEFAULT TRUE,
    members_can_create_internal_repositories  BOOLEAN NOT NULL DEFAULT TRUE,
    members_can_create_pages                  BOOLEAN NOT NULL DEFAULT TRUE,
    members_can_fork_private_repositories     BOOLEAN NOT NULL DEFAULT FALSE,
    members_can_create_teams                  BOOLEAN NOT NULL DEFAULT TRUE,
    web_commit_signoff_required               BOOLEAN NOT NULL DEFAULT FALSE,
    deploy_keys_enabled_for_repositories      BOOLEAN NOT NULL DEFAULT TRUE,
    -- *_enabled_for_new_repositories flags and the push-protection custom link
    security_defaults                         JSONB NOT NULL DEFAULT '{}',
    announcement                              TEXT,
    announcement_expires_at                   TIMESTAMPTZ,
    announcement_user_dismissible             BOOLEAN NOT NULL DEFAULT FALSE,
    immutable_releases                        TEXT NOT NULL DEFAULT 'none'
        CHECK (immutable_releases IN ('all', 'none', 'selected')),
    updated_at                                TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Public (publicized) org membership; GitHub's default is concealed.
ALTER TABLE org_members ADD COLUMN public BOOLEAN NOT NULL DEFAULT FALSE;

-- Repositories a team can access. `permission` is pull/triage/push/maintain/admin or the name
-- of an org custom repository role. Child teams inherit their ancestors' access.
CREATE TABLE team_repos (
    team_id    BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    permission TEXT NOT NULL DEFAULT 'pull',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (team_id, repo_id)
);
CREATE INDEX team_repos_repo ON team_repos (repo_id);
CREATE INDEX team_members_user ON team_members (user_id);
CREATE INDEX teams_parent ON teams (parent_id);
ALTER TABLE teams ADD COLUMN notification_setting TEXT NOT NULL DEFAULT 'notifications_enabled';

-- Custom repository roles: a base role plus extra fine-grained permissions.
CREATE TABLE custom_repo_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    description TEXT,
    base_role   TEXT NOT NULL CHECK (base_role IN ('read', 'triage', 'write', 'maintain')),
    permissions TEXT[] NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX custom_repo_roles_name ON custom_repo_roles (org_id, lower(name));

-- Organization roles. Rows with org_id NULL are GitHub's predefined roles (same ids everywhere).
CREATE TABLE org_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    org_id      BIGINT REFERENCES users(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    description TEXT,
    base_role   TEXT CHECK (base_role IN ('read', 'triage', 'write', 'maintain', 'admin')),
    permissions TEXT[] NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX org_roles_name ON org_roles (COALESCE(org_id, 0), lower(name));
