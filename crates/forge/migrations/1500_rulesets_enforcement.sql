-- Ruleset enforcement (crate::rules): rule suites without evaluate-mode rules have a null
-- evaluation_result (GitHub), and push-ruleset delegated bypass requests.
ALTER TABLE rule_suites ALTER COLUMN evaluation_result DROP NOT NULL;

CREATE TABLE push_bypass_requests (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id             BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    number              BIGINT NOT NULL,
    requester_id        BIGINT REFERENCES users(id) ON DELETE SET NULL,
    requester_name      TEXT NOT NULL DEFAULT '',
    ref                 TEXT NOT NULL,
    -- The commit the requester wants to push (the ref's new value).
    resource_identifier TEXT NOT NULL,
    -- [{ruleset_id, ruleset_name, total_violations, rule_type}]
    data                JSONB NOT NULL DEFAULT '[]',
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'denied', 'approved', 'cancelled', 'completed', 'expired', 'deleted', 'open')),
    requester_comment   TEXT,
    expires_at          TIMESTAMPTZ NOT NULL DEFAULT now() + interval '7 days',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (repo_id, number)
);
CREATE INDEX push_bypass_requests_lookup ON push_bypass_requests (repo_id, resource_identifier);

CREATE TABLE push_bypass_responses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    BIGINT NOT NULL REFERENCES push_bypass_requests(id) ON DELETE CASCADE,
    reviewer_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reviewer_name TEXT NOT NULL DEFAULT '',
    status        TEXT NOT NULL CHECK (status IN ('approved', 'denied', 'dismissed')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX push_bypass_responses_req ON push_bypass_responses (request_id, id);
