-- Repository security advisories (api.github.com's `security-advisories` repository endpoints;
-- not part of GHES 3.22's REST surface) and private vulnerability reports. Private
-- vulnerability reporting itself is the `private_vulnerability_reporting` product in
-- `repo_security_products`.

CREATE TABLE repository_advisories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id             BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    ghsa_id             TEXT NOT NULL UNIQUE,
    cve_id              TEXT,
    summary             TEXT NOT NULL DEFAULT '',
    description         TEXT,
    severity            TEXT,                                   -- critical | high | medium | low
    cvss_vector         TEXT,
    cvss_score          DOUBLE PRECISION,
    cwe_ids             TEXT[] NOT NULL DEFAULT '{}',
    vulnerabilities     JSONB NOT NULL DEFAULT '[]',            -- [{package{ecosystem,name}, vulnerable_version_range, patched_versions, vulnerable_functions}]
    state               TEXT NOT NULL DEFAULT 'draft',          -- triage | draft | published | closed | withdrawn
    author_id           BIGINT REFERENCES users(id) ON DELETE SET NULL,
    publisher_id        BIGINT REFERENCES users(id) ON DELETE SET NULL,
    is_report           BOOLEAN NOT NULL DEFAULT false,         -- created through private vulnerability reporting
    report_accepted     BOOLEAN NOT NULL DEFAULT false,
    collaborating_users BIGINT[] NOT NULL DEFAULT '{}',
    collaborating_teams BIGINT[] NOT NULL DEFAULT '{}',
    cve_requested_at    TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at        TIMESTAMPTZ,
    closed_at           TIMESTAMPTZ,
    withdrawn_at        TIMESTAMPTZ
);
CREATE INDEX repository_advisories_repo ON repository_advisories (repo_id, created_at DESC);

CREATE TABLE repository_advisory_credits (
    advisory_id BIGINT NOT NULL REFERENCES repository_advisories(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,                                  -- analyst | finder | reporter | coordinator | ...
    state       TEXT NOT NULL DEFAULT 'pending',                -- accepted | declined | pending
    PRIMARY KEY (advisory_id, user_id)
);
