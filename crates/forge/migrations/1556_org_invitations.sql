-- Organization invitations (api.github.com: /orgs/{org}/invitations, failed_invitations) and
-- organization blocks (/orgs/{org}/blocks). GHES' PUT /orgs/{org}/memberships/{username} still
-- adds members directly; invitations are the web UI's "Invite member" flow, accepted by the
-- invitee with PATCH /user/memberships/orgs/{org} {"state":"active"}.
CREATE TABLE org_invitations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    invitee_id     BIGINT REFERENCES users(id) ON DELETE CASCADE,
    email          TEXT,
    role           TEXT NOT NULL DEFAULT 'direct_member',
    team_ids       BIGINT[] NOT NULL DEFAULT '{}',
    inviter_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    failed_at      TIMESTAMPTZ,
    failed_reason  TEXT,
    CHECK (invitee_id IS NOT NULL OR email IS NOT NULL)
);
CREATE INDEX org_invitations_org ON org_invitations (org_id);
CREATE INDEX org_invitations_invitee ON org_invitations (invitee_id);
CREATE INDEX org_invitations_email ON org_invitations (lower(email));

CREATE TABLE org_blocks (
    org_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, user_id)
);
