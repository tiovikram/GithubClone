-- apps area (docs/BUILDOUT.md): GitHub Apps and OAuth apps, installations, installation access
-- tokens, user-to-server tokens, the legacy OAuth Authorizations API and migrations (exports).

-- Registered applications. kind 'app' = GitHub App (has a bot user, keys, installations),
-- 'oauth' = OAuth app. Ids start at 2: app id 1 is the built-in synthetic "forge" checks app.
CREATE TABLE apps (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    kind               TEXT NOT NULL DEFAULT 'app' CHECK (kind IN ('app', 'oauth')),
    slug               TEXT NOT NULL,
    name               TEXT NOT NULL,
    owner_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    bot_user_id        BIGINT REFERENCES users(id) ON DELETE SET NULL,
    description        TEXT,
    external_url       TEXT NOT NULL,
    client_id          TEXT NOT NULL UNIQUE,
    client_secret_hash TEXT NOT NULL,
    permissions        JSONB NOT NULL DEFAULT '{}',
    events             TEXT[] NOT NULL DEFAULT '{}',
    public             BOOLEAN NOT NULL DEFAULT FALSE,
    callback_urls      TEXT[] NOT NULL DEFAULT '{}',
    redirect_url       TEXT,
    setup_url          TEXT,
    request_oauth_on_install BOOLEAN NOT NULL DEFAULT FALSE,
    setup_on_update    BOOLEAN NOT NULL DEFAULT FALSE,
    created_by         BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX apps_slug ON apps (lower(slug));
CREATE UNIQUE INDEX apps_name ON apps (lower(name)) WHERE kind = 'app';
CREATE INDEX apps_owner ON apps (owner_id);

-- Public halves of the app's RSA private keys (RFC 8017 RSAPublicKey DER). The private key is
-- shown to the owner once and never stored.
CREATE TABLE app_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id      BIGINT NOT NULL REFERENCES apps(id) ON DELETE CASCADE,
    public_key  BYTEA NOT NULL,
    fingerprint TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX app_keys_app ON app_keys (app_id);

-- Manifest flow: a code issued for a manifest, exchanged once by
-- POST /app-manifests/{code}/conversions (valid for one hour).
CREATE TABLE app_manifest_codes (
    code_hash  TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    owner_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    manifest   JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);

-- Installations on a user or organization account (target_id), or on the enterprise
-- (target_type 'Enterprise', target_id NULL).
CREATE TABLE app_installations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id               BIGINT NOT NULL REFERENCES apps(id) ON DELETE CASCADE,
    target_id            BIGINT REFERENCES users(id) ON DELETE CASCADE,
    target_type          TEXT NOT NULL CHECK (target_type IN ('User', 'Organization', 'Enterprise')),
    repository_selection TEXT NOT NULL DEFAULT 'all' CHECK (repository_selection IN ('all', 'selected')),
    permissions          JSONB NOT NULL DEFAULT '{}',
    events               TEXT[] NOT NULL DEFAULT '{}',
    installer_id         BIGINT REFERENCES users(id) ON DELETE SET NULL,
    suspended_at         TIMESTAMPTZ,
    suspended_by         BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX app_installations_target ON app_installations (app_id, COALESCE(target_id, 0));
CREATE INDEX app_installations_target_id ON app_installations (target_id);

CREATE TABLE app_installation_repos (
    installation_id BIGINT NOT NULL REFERENCES app_installations(id) ON DELETE CASCADE,
    repo_id         BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    PRIMARY KEY (installation_id, repo_id)
);
CREATE INDEX app_installation_repos_repo ON app_installation_repos (repo_id);

-- Installation access tokens (ghs_, 1 hour). repository_ids NULL = every repository of the
-- installation; permissions = the token's (subset of the installation's) permissions.
CREATE TABLE app_installation_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id BIGINT NOT NULL REFERENCES app_installations(id) ON DELETE CASCADE,
    token_hash      TEXT NOT NULL UNIQUE,
    repository_ids  BIGINT[],
    permissions     JSONB NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX app_installation_tokens_expires ON app_installation_tokens (expires_at);

-- App webhooks: a `webhooks` row owned by an app (repo_id and org_id NULL).
ALTER TABLE webhooks ADD COLUMN app_id BIGINT REFERENCES apps(id) ON DELETE CASCADE;
CREATE INDEX webhooks_app ON webhooks (app_id) WHERE app_id IS NOT NULL;

-- OAuth grants (one per user and application) and authorizations (one per token). Covers the
-- legacy OAuth Authorizations API, device-flow tokens of OAuth/GitHub Apps and GitHub App
-- user-to-server tokens (ghu_, with a ghr_ refresh token). client_id '00000000000000000000'
-- is a personal authorization without an application.
CREATE TABLE oauth_grants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    app_id     BIGINT REFERENCES apps(id) ON DELETE CASCADE,
    client_id  TEXT NOT NULL,
    app_name   TEXT NOT NULL,
    app_url    TEXT NOT NULL,
    scopes     TEXT[] NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, client_id)
);

CREATE TABLE oauth_authorizations (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id           BIGINT NOT NULL REFERENCES oauth_grants(id) ON DELETE CASCADE,
    user_id            BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_id           BIGINT NOT NULL UNIQUE REFERENCES tokens(id) ON DELETE CASCADE,
    app_id             BIGINT REFERENCES apps(id) ON DELETE CASCADE,
    client_id          TEXT NOT NULL,
    note               TEXT,
    note_url           TEXT,
    fingerprint        TEXT,
    scopes             TEXT[] NOT NULL DEFAULT '{}',
    hashed_token       TEXT NOT NULL,
    token_last_eight   TEXT NOT NULL,
    refresh_hash       TEXT UNIQUE,
    refresh_expires_at TIMESTAMPTZ,
    -- scope-token: restrictions on a GitHub App user-to-server token
    target_id          BIGINT REFERENCES users(id) ON DELETE CASCADE,
    repository_ids     BIGINT[],
    permissions        JSONB,
    expires_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX oauth_authorizations_user ON oauth_authorizations (user_id, id);
CREATE INDEX oauth_authorizations_grant ON oauth_authorizations (grant_id);
CREATE INDEX oauth_authorizations_hash ON oauth_authorizations (hashed_token);

-- Migrations (exports) of user or organization repositories.
CREATE TABLE migrations (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid                   TEXT NOT NULL UNIQUE,
    owner_id               BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_by             BIGINT REFERENCES users(id) ON DELETE SET NULL,
    state                  TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'exporting', 'exported', 'failed')),
    lock_repositories      BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_metadata       BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_git_data       BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_attachments    BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_releases       BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_owner_projects BOOLEAN NOT NULL DEFAULT FALSE,
    org_metadata_only      BOOLEAN NOT NULL DEFAULT FALSE,
    exclude                TEXT[] NOT NULL DEFAULT '{}',
    archive_key            TEXT,
    archive_size           BIGINT,
    archive_deleted        BOOLEAN NOT NULL DEFAULT FALSE,
    error                  TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX migrations_owner ON migrations (owner_id, id DESC);

CREATE TABLE migration_repos (
    migration_id BIGINT NOT NULL REFERENCES migrations(id) ON DELETE CASCADE,
    repo_id      BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    PRIMARY KEY (migration_id, repo_id)
);

-- Repositories locked by a migration (lock_repositories): pushes and REST writes are refused
-- until the repository is unlocked.
CREATE TABLE migration_locks (
    repo_id      BIGINT PRIMARY KEY REFERENCES repositories(id) ON DELETE CASCADE,
    migration_id BIGINT NOT NULL REFERENCES migrations(id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
