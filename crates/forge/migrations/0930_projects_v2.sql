-- GitHub Projects (v2) (area ghcompat): projects owned by a user or organization, their fields,
-- items (issues, pull requests or draft issues) and per-item field values. Served through
-- GraphQL only, like GitHub (`gh project ...`).

CREATE TABLE projects_v2 (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    number            BIGINT NOT NULL,
    title             TEXT NOT NULL,
    short_description TEXT,
    readme            TEXT,
    public            BOOLEAN NOT NULL DEFAULT FALSE,
    closed            BOOLEAN NOT NULL DEFAULT FALSE,
    closed_at         TIMESTAMPTZ,
    template          BOOLEAN NOT NULL DEFAULT FALSE,
    creator_id        BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner_id, number)
);

-- data_type: ProjectV2FieldType. `options` holds single-select options
-- [{id, name, color, description}]; `config` holds the iteration configuration
-- {duration, start_day, iterations: [{id, title, start_date, duration}]}.
CREATE TABLE projects_v2_fields (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects_v2(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    data_type  TEXT NOT NULL CHECK (data_type IN ('ASSIGNEES', 'DATE', 'ITERATION', 'LABELS', 'LINKED_PULL_REQUESTS',
        'MILESTONE', 'NUMBER', 'REPOSITORY', 'REVIEWERS', 'SINGLE_SELECT', 'TEXT', 'TITLE', 'PARENT_ISSUE',
        'SUB_ISSUES_PROGRESS', 'TRACKED_BY', 'TRACKS')),
    options    JSONB NOT NULL DEFAULT '[]',
    config     JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX projects_v2_fields_name ON projects_v2_fields (project_id, lower(name));

-- An item is an issue/pull request (issue_id) or a draft issue (draft_title/draft_body).
CREATE TABLE projects_v2_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT NOT NULL REFERENCES projects_v2(id) ON DELETE CASCADE,
    issue_id     BIGINT REFERENCES issues(id) ON DELETE CASCADE,
    draft_title  TEXT,
    draft_body   TEXT,
    archived     BOOLEAN NOT NULL DEFAULT FALSE,
    creator_id   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((issue_id IS NULL) <> (draft_title IS NULL)),
    UNIQUE (project_id, issue_id)
);
CREATE INDEX projects_v2_items_project ON projects_v2_items (project_id, id);
CREATE INDEX projects_v2_items_issue ON projects_v2_items (issue_id);

-- Values of custom fields (text, number, date, single select option id, iteration id).
CREATE TABLE projects_v2_item_values (
    item_id    BIGINT NOT NULL REFERENCES projects_v2_items(id) ON DELETE CASCADE,
    field_id   BIGINT NOT NULL REFERENCES projects_v2_fields(id) ON DELETE CASCADE,
    value      JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (item_id, field_id)
);

CREATE TABLE projects_v2_repositories (
    project_id BIGINT NOT NULL REFERENCES projects_v2(id) ON DELETE CASCADE,
    repo_id    BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, repo_id)
);
CREATE INDEX projects_v2_repositories_repo ON projects_v2_repositories (repo_id);
