-- Enterprise audit log (real events: authentication, admin actions, ...).
CREATE TABLE ent_audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action     TEXT NOT NULL,
    actor_id   BIGINT,
    actor      TEXT,
    user_id    BIGINT,
    user_login TEXT,
    org_id     BIGINT,
    org        TEXT,
    repo_id    BIGINT,
    repo       TEXT,
    actor_ip   TEXT,
