-- enterprise area (docs/BUILDOUT.md): forge is a single-enterprise, GHES-like install. Site
-- admins (users.site_admin) are the enterprise owners. Tables are prefixed `ent_`.

-- Users: suspension (suspended users cannot authenticate by any means) -----------------------
ALTER TABLE users ADD COLUMN suspended_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN suspension_reason TEXT;

-- Impersonation OAuth tokens (POST /admin/users/{u}/authorizations) act as the user.
ALTER TABLE tokens ADD COLUMN impersonation BOOLEAN NOT NULL DEFAULT FALSE;

-- Global webhooks: rows with repo_id and org_id both NULL and is_global set.
ALTER TABLE webhooks ADD COLUMN is_global BOOLEAN NOT NULL DEFAULT FALSE;

-- /admin/keys lists user keys and deploy keys in one id space (GitHub has a single table):
-- deploy keys draw ids from the ssh_keys sequence from now on; existing collisions are renumbered.
ALTER TABLE deploy_keys ALTER COLUMN id DROP IDENTITY IF EXISTS;
SELECT setval(pg_get_serial_sequence('ssh_keys', 'id'),
    GREATEST((SELECT COALESCE(max(id), 0) FROM ssh_keys), (SELECT COALESCE(max(id), 0) FROM deploy_keys), 1));
UPDATE deploy_keys SET id = nextval(pg_get_serial_sequence('ssh_keys', 'id')) WHERE id IN (SELECT id FROM ssh_keys);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE deploy_keys ALTER COLUMN id SET DEFAULT nextval(%L)', pg_get_serial_sequence('ssh_keys', 'id'));
END $$;

-- Key/value enterprise settings: announcement, actions policy, code security defaults,
