CREATE TABLE ent_ldap_sync_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         TEXT NOT NULL,
    subject_id   BIGINT NOT NULL,
    ldap_dn      TEXT,
    requested_by BIGINT,
