CREATE INDEX ent_audit_log_created ON ent_audit_log (created_at DESC, id DESC);
CREATE INDEX ent_audit_log_action ON ent_audit_log (action);

CREATE TABLE ent_audit_streams (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_type     TEXT NOT NULL,
