);

-- Pre-receive hooks -------------------------------------------------------------------------
-- An environment is a tarball (downloaded from image_url into object storage at
-- pre-receive-environments/{id}/{digest}.tar.gz) the hook script runs against. The built-in
-- default environment runs scripts with the host's /bin/sh tools.
CREATE TABLE ent_pre_receive_environments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL,
    image_url           TEXT NOT NULL,
    default_environment BOOLEAN NOT NULL DEFAULT FALSE,
    download_state      TEXT NOT NULL DEFAULT 'not_started',
    downloaded_at       TIMESTAMPTZ,
    download_message    TEXT,
    object_key          TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ent_pre_receive_environments_name ON ent_pre_receive_environments (lower(name));
INSERT INTO ent_pre_receive_environments (name, image_url, default_environment, download_state, downloaded_at)
    VALUES ('default', 'githubenterprise://internal', TRUE, 'success', now());

CREATE TABLE ent_pre_receive_hooks (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                           TEXT NOT NULL,
    script                         TEXT NOT NULL,
    script_repo_id                 BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    environment_id                 BIGINT NOT NULL REFERENCES ent_pre_receive_environments(id),
    enforcement                    TEXT NOT NULL DEFAULT 'disabled' CHECK (enforcement IN ('enabled', 'disabled', 'testing')),
    allow_downstream_configuration BOOLEAN NOT NULL DEFAULT FALSE,
    created_at                     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ent_pre_receive_hooks_name ON ent_pre_receive_hooks (lower(name));

CREATE TABLE ent_pre_receive_org_settings (
    hook_id                        BIGINT NOT NULL REFERENCES ent_pre_receive_hooks(id) ON DELETE CASCADE,
    org_id                         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    enforcement                    TEXT NOT NULL CHECK (enforcement IN ('enabled', 'disabled', 'testing')),
    allow_downstream_configuration BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (hook_id, org_id)
);
CREATE TABLE ent_pre_receive_repo_settings (
    hook_id     BIGINT NOT NULL REFERENCES ent_pre_receive_hooks(id) ON DELETE CASCADE,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    enforcement TEXT NOT NULL CHECK (enforcement IN ('enabled', 'disabled', 'testing')),
    PRIMARY KEY (hook_id, repo_id)
);

-- Enterprise teams --------------------------------------------------------------------------
CREATE TABLE ent_teams (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                        TEXT NOT NULL,
    slug                        TEXT NOT NULL UNIQUE,
    description                 TEXT,
    sync_to_organizations       TEXT NOT NULL DEFAULT 'disabled',
    organization_selection_type TEXT NOT NULL DEFAULT 'disabled',
    group_id                    TEXT,
    notification_setting        TEXT NOT NULL DEFAULT 'notifications_enabled',
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE ent_team_members (
    team_id    BIGINT NOT NULL REFERENCES ent_teams(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (team_id, user_id)
);
CREATE TABLE ent_team_orgs (
    team_id    BIGINT NOT NULL REFERENCES ent_teams(id) ON DELETE CASCADE,
    org_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (team_id, org_id)
);
-- Organization memberships that exist only because of an enterprise team assignment (so
-- removing the assignment removes exactly those memberships, never pre-existing ones).
CREATE TABLE ent_org_grants (
    team_id BIGINT NOT NULL REFERENCES ent_teams(id) ON DELETE CASCADE,
    org_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, org_id, user_id)
);

-- SCIM provisioning ----------------------------------------------------------------------------
CREATE TABLE ent_scim_users (
    id          TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    external_id TEXT,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    data        JSONB NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ent_scim_users_external ON ent_scim_users (external_id) WHERE external_id IS NOT NULL;
-- A SCIM group is mirrored as an enterprise-wide `external_groups` row (orgs area, org_id NULL)
-- whose `external_group_members` are the group's members, so org teams can link to it.
-- (No FK: external_groups is created by a later-numbered migration.)
CREATE TABLE ent_scim_groups (
    id           TEXT PRIMARY KEY,
    external_group_id BIGINT NOT NULL,
    external_id  TEXT,
    display_name TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ent_scim_groups_external ON ent_scim_groups (external_id) WHERE external_id IS NOT NULL;

-- Enterprise custom property definitions (kind 'repo': repository properties defined at
-- enterprise level; kind 'org': organization properties, whose values live in the orgs area's
-- org_custom_property_values).
CREATE TABLE ent_custom_properties (
    kind                    TEXT NOT NULL CHECK (kind IN ('repo', 'org')),
    property_name           TEXT NOT NULL,
    value_type              TEXT NOT NULL,
    required                BOOLEAN NOT NULL DEFAULT FALSE,
    default_value           JSONB,
    description             TEXT,
    allowed_values          TEXT[],
    values_editable_by      TEXT,
    require_explicit_values BOOLEAN NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (kind, property_name)
);

