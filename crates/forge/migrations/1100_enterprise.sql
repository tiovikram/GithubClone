-- Live migrations (records and state machine; forge transfers no data to the target).
CREATE TABLE ent_live_migrations (
    id                        TEXT PRIMARY KEY,
    source_organization_login TEXT NOT NULL,
    source_repository_name    TEXT NOT NULL,
    target_organization_login TEXT NOT NULL,
    target_repository_name    TEXT NOT NULL,
    target_api_endpoint       TEXT NOT NULL,
    pat_name                  TEXT NOT NULL,
    target_visibility         TEXT,
    status                    TEXT NOT NULL DEFAULT 'created',
    messages                  JSONB NOT NULL DEFAULT '[]',
    created_by                BIGINT,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at                TIMESTAMPTZ,
    completed_at              TIMESTAMPTZ,
    expires_at                TIMESTAMPTZ
);

-- Management API: forge processes seen recently (each pod records a heartbeat) and config runs.
CREATE TABLE ent_nodes (
    uuid         TEXT PRIMARY KEY,
    hostname     TEXT NOT NULL,
    version      TEXT NOT NULL,
    started_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE ent_config_runs (
    id          TEXT PRIMARY KEY,
    requested_by BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    successful  BOOLEAN,
    events      JSONB NOT NULL DEFAULT '[]'
);
