-- SSH (area `ssh`): shared host key, deploy keys, key usage tracking.

-- Host keys shared by every pod, so a horizontally scaled Deployment presents one identity.
-- Generated once by the first pod that needs it (INSERT .. ON CONFLICT DO NOTHING).
CREATE TABLE ssh_host_keys (
    algorithm   TEXT PRIMARY KEY,
    private_key TEXT NOT NULL,          -- OpenSSH private key format (unencrypted)
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE ssh_keys ADD COLUMN last_used TIMESTAMPTZ;

CREATE INDEX ssh_keys_user_idx ON ssh_keys (user_id, id);

-- Per-repository deploy keys. Fingerprints are unique here and must not collide with
-- ssh_keys either (checked by the service layer: a key identifies exactly one principal).
CREATE TABLE deploy_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    key         TEXT NOT NULL,
    fingerprint TEXT NOT NULL UNIQUE,
    read_only   BOOLEAN NOT NULL DEFAULT true,
    added_by_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used   TIMESTAMPTZ
);

CREATE INDEX deploy_keys_repo_idx ON deploy_keys (repo_id, id);
