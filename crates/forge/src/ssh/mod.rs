// ---------------------------------------------------------------------------------------------
// ssh_url for repository JSON

static URL_PREFIXES: LazyLock<RwLock<HashMap<String, String>>> = LazyLock::new(Default::default);

/// Records the SSH clone URL prefix for a server's base URL (called from `build_state`). Keyed by
/// base URL so several in-process servers (tests) can use different SSH ports.
pub fn register_config(cfg: &Config) {
    if let Some(prefix) = cfg.ssh_url_prefix() {
        URL_PREFIXES.write().unwrap().insert(cfg.base_url.clone(), prefix);
    }
}

/// `ssh_url` for a repository: `git@host:o/r.git`, or `ssh://git@host:port/o/r.git` when SSH
/// runs on a non-standard port (FORGE_SSH_URL_HOST / FORGE_SSH_URL_PORT / FORGE_SSH_LISTEN).
pub fn ssh_url(base: &str, full_name: &str) -> String {
    let prefix = URL_PREFIXES.read().unwrap().get(base).cloned();
    let prefix = prefix.unwrap_or_else(|| format!("git@{}:", crate::json::repo::host_of(base)));
    format!("{prefix}{full_name}.git")
}

