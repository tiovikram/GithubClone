/// Loads the host key: `FORGE_SSH_HOST_KEY` if set, else the ed25519 key stored in Postgres
/// (generated by whichever pod gets there first), so every replica presents the same identity.
pub async fn host_key(state: &AppState) -> anyhow::Result<PrivateKey> {
    if let Some(path) = &state.cfg.ssh_host_key {
        return PrivateKey::read_openssh_file(path).with_context(|| format!("reading SSH host key {}", path.display()));
    }
    let alg = "ssh-ed25519";
    let load = || async {
        sqlx::query_scalar::<_, String>("SELECT private_key FROM ssh_host_keys WHERE algorithm = $1")
            .bind(alg)
            .fetch_optional(&state.db)
            .await
    };
    let pem = match load().await? {
        Some(p) => p,
        None => {
            let key = PrivateKey::random(&mut rand::rng(), Algorithm::Ed25519)?;
            let pem = key.to_openssh(LineEnding::LF)?.to_string();
            sqlx::query("INSERT INTO ssh_host_keys (algorithm, private_key) VALUES ($1, $2) ON CONFLICT DO NOTHING")
                .bind(alg)
                .bind(&pem)
                .execute(&state.db)
                .await?;
            load().await?.context("host key vanished")?
        }
    };
    Ok(PrivateKey::from_openssh(pem.as_bytes())?)
}

fn server_config(key: PrivateKey) -> russh::server::Config {
    russh::server::Config {
        server_id: russh::SshId::Standard("SSH-2.0-forge".into()),
        methods: MethodSet::from(&[MethodKind::PublicKey][..]),
        auth_rejection_time: Duration::from_millis(500),
        auth_rejection_time_initial: Some(Duration::ZERO),
        keys: vec![key],
        // Pushes hold the session silent while the pack is indexed and committed.
        inactivity_timeout: Some(Duration::from_secs(3600)),
        keepalive_interval: Some(Duration::from_secs(30)),
        keepalive_max: 6,
        nodelay: true,
        ..Default::default()
    }
}

/// Binds `FORGE_SSH_LISTEN` (if set) and serves SSH in the background. Returns the bound address.
pub async fn start(state: &AppState) -> anyhow::Result<Option<SocketAddr>> {
    let Some(listen) = state.cfg.ssh_listen.clone() else { return Ok(None) };
    let listener = TcpListener::bind(&listen).await.with_context(|| format!("binding SSH listener {listen}"))?;
    serve_listener(state.clone(), listener).await.map(Some)
}

/// Serves SSH on an already bound listener (tests bind port 0 themselves).
pub async fn serve_listener(state: AppState, listener: TcpListener) -> anyhow::Result<SocketAddr> {
    let addr = listener.local_addr()?;
    let key = host_key(&state).await?;
    tracing::info!(fingerprint = %key.public_key().fingerprint(Default::default()), "forge SSH listening on {addr}");
    let config = Arc::new(server_config(key));
    tokio::spawn(async move {
        let mut server = SshServer { state };
        if let Err(e) = server.run_on_socket(config, &listener).await {
            tracing::error!(error = %e, "SSH server stopped");
        }
    });
    Ok(addr)
}

struct SshServer {
    state: AppState,
}

impl russh::server::Server for SshServer {
    type Handler = SshSession;

    fn new_client(&mut self, peer: Option<SocketAddr>) -> SshSession {
        SshSession { state: self.state.clone(), peer, owner: None, channels: HashMap::new(), protocol: HashMap::new() }
    }

    fn handle_session_error(&mut self, error: anyhow::Error) {
        tracing::debug!(error = %format!("{error:#}"), "SSH session error");
    }
}

pub struct SshSession {
    state: AppState,
    peer: Option<SocketAddr>,
    owner: Option<KeyOwner>,
    channels: HashMap<ChannelId, Channel<Msg>>,
    /// `GIT_PROTOCOL` env per channel.
    protocol: HashMap<ChannelId, String>,
}

impl SshSession {
    async fn lookup(&self, user: &str, key: &PublicKey) -> anyhow::Result<Option<KeyOwner>> {
        if user != "git" {
            return Ok(None);
        }
        let owner = keys::owner_by_fingerprint(&self.state.db, &keys::fingerprint(key)).await?;
        Ok(owner.filter(|o| match o {
            KeyOwner::User { user, .. } => user.kind == "User",
            KeyOwner::Deploy(_) => true,
        }))
    }

    fn display_name(&self) -> String {
        match &self.owner {
            Some(KeyOwner::User { user, .. }) => user.login.clone(),
            Some(KeyOwner::Deploy(d)) => format!("deploy key {}", d.title),
            None => "anonymous".into(),
        }
    }
}

impl russh::server::Handler for SshSession {
    type Error = anyhow::Error;

    async fn auth_publickey_offered(&mut self, user: &str, key: &PublicKey) -> Result<Auth, Self::Error> {
        Ok(if self.lookup(user, key).await?.is_some() { Auth::Accept } else { Auth::reject() })
    }

    async fn auth_publickey(&mut self, user: &str, key: &PublicKey) -> Result<Auth, Self::Error> {
        match self.lookup(user, key).await? {
            Some(owner) => {
                keys::touch(&self.state.db, &owner).await;
                tracing::debug!(peer = ?self.peer, "SSH auth ok");
                self.owner = Some(owner);
                Ok(Auth::Accept)
            }
            None => Ok(Auth::reject()),
        }
    }

    async fn channel_open_session(
        &mut self,
        channel: Channel<Msg>,
        reply: ChannelOpenHandle,
        _session: &mut Session,
    ) -> Result<(), Self::Error> {
        if self.channels.len() >= 8 {
            return Ok(()); // dropping `reply` rejects
        }
        self.channels.insert(channel.id(), channel);
        reply.accept().await;
        Ok(())
    }

    async fn channel_close(&mut self, channel: ChannelId, _session: &mut Session) -> Result<(), Self::Error> {
        self.channels.remove(&channel);
        self.protocol.remove(&channel);
        Ok(())
    }

    async fn env_request(
        &mut self,
        channel: ChannelId,
        name: &str,
        value: &str,
        session: &mut Session,
    ) -> Result<(), Self::Error> {
        if name == "GIT_PROTOCOL" && command::valid_git_protocol(value) {
            self.protocol.insert(channel, value.to_string());
            session.channel_success(channel)?;
        } else {
            session.channel_failure(channel)?;
        }
        Ok(())
    }

    async fn pty_request(
        &mut self,
        channel: ChannelId,
        _term: &str,
        _col_width: u32,
        _row_height: u32,
        _pix_width: u32,
        _pix_height: u32,
        _modes: &[(russh::Pty, u32)],
        session: &mut Session,
    ) -> Result<(), Self::Error> {
        session.channel_failure(channel)?;
        Ok(())
    }

    async fn shell_request(&mut self, channel: ChannelId, session: &mut Session) -> Result<(), Self::Error> {
        session.channel_success(channel)?;
        let msg = format!(
            "Hi {}! You've successfully authenticated, but forge does not provide shell access.\r\n",
            self.display_name()
        );
        session.extended_data(channel, 1, Bytes::from(msg))?;
        session.exit_status_request(channel, 1)?;
        session.eof(channel)?;
        session.close(channel)?;
        self.channels.remove(&channel);
        Ok(())
    }

    async fn subsystem_request(&mut self, channel: ChannelId, _name: &str, session: &mut Session) -> Result<(), Self::Error> {
        session.channel_failure(channel)?;
        Ok(())
    }

    async fn exec_request(&mut self, channel: ChannelId, data: &[u8], session: &mut Session) -> Result<(), Self::Error> {
        let (Some(ch), Some(owner)) = (self.channels.remove(&channel), self.owner.clone()) else {
            session.channel_failure(channel)?;
            return Ok(());
        };
        session.channel_success(channel)?;
        let cmd = String::from_utf8_lossy(data).into_owned();
        let proto = self.protocol.remove(&channel);
        let state = self.state.clone();
        let display = self.display_name();
        tokio::spawn(async move {
            let (read, write) = ch.split();
            let code = match exec(&state, &owner, &display, read, &write, &cmd, proto).await {
                Ok(code) => code,
                Err(e) => {
                    tracing::error!(error = %format!("{e:#}"), command = %cmd, "SSH exec failed");
                    let _ = write.extended_data_bytes(1, Bytes::from_static(b"ERROR: internal server error\n")).await;
                    1
                }
            };
            let _ = write.exit_status(code).await;
            let _ = write.eof().await;
            let _ = write.close().await;
        });
        Ok(())
    }
}

