type Writer = ChannelWriteHalf<Msg>;

async fn stderr(w: &Writer, msg: impl Into<String>) {
    let _ = w.extended_data_bytes(1, Bytes::from(msg.into())).await;
}

/// Finds a repository by owner/name regardless of visibility (deploy keys bypass user perms).
async fn find_repo(state: &AppState, owner: &str, name: &str) -> anyhow::Result<Option<(Repo, User)>> {
    let Ok(owner) = db::user_by_login(&state.db, owner).await else { return Ok(None) };
    let repo: Option<Repo> = sqlx::query_as("SELECT * FROM repositories WHERE owner_id = $1 AND lower(name) = lower($2)")
        .bind(owner.id)
        .bind(name)
        .fetch_optional(&state.db)
        .await?;
    Ok(repo.map(|r| (r, owner)))
}

/// Resolves the repository and the principal's permission on it. `None` = invisible (404).
async fn authorize(state: &AppState, owner: &KeyOwner, gc: &GitCommand) -> anyhow::Result<Option<(RepoCtx, User)>> {
    match owner {
        KeyOwner::User { user, .. } => match db::load_repo(&state.db, Some(user), &gc.owner, &gc.repo).await {
            Ok(ctx) => Ok(Some((ctx, user.clone()))),
            Err(e) if e.status == axum::http::StatusCode::NOT_FOUND => Ok(None),
            Err(e) => anyhow::bail!("load repo: {}", e.message),
        },
        KeyOwner::Deploy(dk) => {
            let Some((repo, repo_owner)) = find_repo(state, &gc.owner, &gc.repo).await? else { return Ok(None) };
            if repo.id != dk.repo_id {
                return Ok(None);
            }
            let perm = if dk.read_only { Perm::Read } else { Perm::Write };
            // Pushes are attributed to whoever added the key (falling back to the repo owner).
            let pusher = match dk.added_by_id {
                Some(id) => db::user_by_id(&state.db, id).await.unwrap_or_else(|_| repo_owner.clone()),
                None => repo_owner.clone(),
            };
            Ok(Some((RepoCtx { repo, owner: repo_owner, perm }, pusher)))
        }
    }
}

async fn exec(
    state: &AppState,
    owner: &KeyOwner,
    display: &str,
    read: ChannelReadHalf,
    write: &Writer,
    cmd: &str,
    proto: Option<String>,
) -> anyhow::Result<u32> {
    let gc = match command::parse(cmd) {
        Ok(gc) => gc,
        Err(ParseError::NotGit) => {
            let shown: String = cmd.chars().take(100).collect();
            stderr(
                write,
                format!(
                    "Invalid command: '{shown}'\nHi {display}! You've successfully authenticated, but forge does not provide shell access.\n"
                ),
            )
            .await;
            return Ok(1);
        }
        Err(ParseError::BadPath) => {
            stderr(write, "ERROR: Repository not found.\n").await;
            return Ok(1);
        }
    };
    let need = if gc.service == Service::ReceivePack { Perm::Write } else { Perm::Read };
    let Some((ctx, actor)) = authorize(state, owner, &gc).await? else {
        stderr(write, "ERROR: Repository not found.\n").await;
        return Ok(1);
    };
    if ctx.perm < need {
        let who = match owner {
            KeyOwner::User { user, .. } => user.login.clone(),
            KeyOwner::Deploy(_) => "deploy key".into(),
        };
        stderr(write, format!("ERROR: Permission to {}.git denied to {who}.\n", ctx.full_name())).await;
        return Ok(1);
    }
    match gc.service {
        Service::UploadPack | Service::UploadArchive => serve_read(state, &ctx, gc.service, read, write, proto).await,
        Service::ReceivePack => {
            if ctx.repo.archived {
                stderr(write, "ERROR: This repository was archived so it is read-only.\n").await;
                return Ok(1);
            }
            serve_push(state, &ctx, &actor, read, write, proto).await
        }
    }
}

/// Copies client channel data into the child's stdin until EOF/close; optionally taps it.
async fn pump_in(
    mut read: ChannelReadHalf,
    mut stdin: tokio::process::ChildStdin,
    tap: Option<Arc<Mutex<PushRequestParser>>>,
) {
    while let Some(msg) = read.wait().await {
        match msg {
            ChannelMsg::Data { data } => {
                if let Some(t) = &tap {
                    t.lock().unwrap().feed(&data);
                }
                if stdin.write_all(&data).await.is_err() {
                    break;
                }
            }
            ChannelMsg::Eof | ChannelMsg::Close => break,
            _ => {}
        }
    }
    let _ = stdin.shutdown().await;
}

/// Forwards a child pipe to the channel (stdout, or stderr as extended data 1).
async fn forward(mut src: impl AsyncRead + Unpin, w: &Writer, ext: Option<u32>) -> std::io::Result<()> {
    let mut buf = vec![0u8; 32 * 1024];
    loop {
        let n = src.read(&mut buf).await?;
        if n == 0 {
            return Ok(());
        }
        let data = Bytes::copy_from_slice(&buf[..n]);
        let sent = match ext {
            None => w.data_bytes(data).await,
            Some(e) => w.extended_data_bytes(e, data).await,
        };
        if sent.is_err() {
            return Err(std::io::Error::new(std::io::ErrorKind::BrokenPipe, "SSH channel closed"));
        }
    }
}

/// Forwards receive-pack's stdout up to the end of the ref advertisement (first flush-pkt) and
/// buffers everything after it (the report-status and sideband progress), returning the buffer.
async fn forward_advertisement(mut src: impl AsyncRead + Unpin, w: &Writer) -> std::io::Result<Vec<u8>> {
    let mut finder = command::FlushFinder::default();
    let mut held = Vec::new();
    let mut buf = vec![0u8; 32 * 1024];
    loop {
        let n = src.read(&mut buf).await?;
        if n == 0 {
            return Ok(held);
        }
        let chunk = &buf[..n];
        if finder.done || finder.broken {
            held.extend_from_slice(chunk);
            continue;
        }
        let split = finder.feed(chunk).unwrap_or(n);
        if w.data_bytes(Bytes::copy_from_slice(&chunk[..split])).await.is_err() {
            return Err(std::io::Error::new(std::io::ErrorKind::BrokenPipe, "SSH channel closed"));
        }
        held.extend_from_slice(&chunk[split..]);
    }
}

async fn serve_read(
    state: &AppState,
    ctx: &RepoCtx,
    service: Service,
    read: ChannelReadHalf,
    write: &Writer,
    proto: Option<String>,
) -> anyhow::Result<u32> {
    let path = state.git.sync(ctx.repo.id).await?;
    let mut cmd = state.git.git.command(&path);
    cmd.args([service.git_subcommand(), "."]).stdin(Stdio::piped()).stdout(Stdio::piped()).stderr(Stdio::piped());
    if let Some(p) = proto {
        cmd.env("GIT_PROTOCOL", p);
    }
    let mut child = cmd.spawn()?;
    let stdin = child.stdin.take().unwrap();
    let stdout = child.stdout.take().unwrap();
    let errout = child.stderr.take().unwrap();
    let pump = tokio::spawn(pump_in(read, stdin, None));
    let (out, _, status) = tokio::join!(forward(stdout, write, None), forward(errout, write, Some(1)), child.wait());
    pump.abort();
    let status = status?;
    if out.is_err() {
        return Ok(1);
    }
    Ok(status.code().unwrap_or(1) as u32)
}

/// Push: `git receive-pack` runs inside `GitStore::write` (cluster-wide lock, storage commit).
/// The ref advertisement is streamed live; everything receive-pack writes after it (the
/// report-status and progress) is held back until the manifest commit succeeds, so the client
/// can never see "ok" for a ref that is not durably stored. If the commit fails, the client gets
/// a synthesized report with every ref rejected and the exit status is 1.
async fn serve_push(
    state: &AppState,
    ctx: &RepoCtx,
    pusher: &User,
    read: ChannelReadHalf,
    write: &Writer,
    proto: Option<String>,
) -> anyhow::Result<u32> {
    let git = state.git.git.clone();
    let tap = Arc::new(Mutex::new(PushRequestParser::default()));
    let tap2 = tap.clone();
    let result = state
        .git
        .write(ctx.repo.id, |path| async move {
            let mut cmd = git.command(&path);
            cmd.args(["receive-pack", "."]).stdin(Stdio::piped()).stdout(Stdio::piped()).stderr(Stdio::piped());
            if let Some(p) = proto {
                cmd.env("GIT_PROTOCOL", p);
            }
            let mut child = cmd.spawn()?;
            let stdin = child.stdin.take().unwrap();
            let stdout = child.stdout.take().unwrap();
            let errout = child.stderr.take().unwrap();
            let pump = tokio::spawn(pump_in(read, stdin, Some(tap2)));
            let (held, _, status) =
                tokio::join!(forward_advertisement(stdout, write), forward(errout, write, Some(1)), child.wait());
            pump.abort();
            let status = status?;
            let held = held?;
            if !status.success() {
                anyhow::bail!("receive-pack exited with {status}");
            }
            Ok(held)
        })
        .await;
    match result {
        Ok((report, updates)) => {
            if let Err(e) = crate::events::on_push(state, ctx, pusher, &updates).await {
                tracing::error!(error = %format!("{e:#}"), "post-push processing failed");
            }
            if write.data_bytes(Bytes::from(report)).await.is_err() {
                return Ok(1);
            }
            Ok(0)
        }
        Err(e) => {
            tracing::error!(error = %format!("{e:#}"), repo = %ctx.full_name(), "SSH push failed");
            let req = tap.lock().unwrap().req.clone();
            if req.complete && req.report_status && !req.refs.is_empty() {
                let _ = write.data_bytes(Bytes::from(command::failure_report(&req, "storage commit failed"))).await;
            }
            stderr(write, "ERROR: push failed: could not commit to storage; no refs were updated.\n").await;
            Ok(1)
        }
    }
}
