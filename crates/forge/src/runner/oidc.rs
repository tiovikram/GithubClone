/// Issuer path below the base URL (GHES: `https://HOSTNAME/_services/token`).
pub const ISSUER_PATH: &str = "/_services/token";
/// Path of the ID-token endpoint (the runner prefixes it with the URL it reaches forge at).
pub const TOKEN_PATH: &str = "/_services/token/idtoken?api-version=2.0";
const TOKEN_TTL_SECS: i64 = 300;

const CLAIMS_SUPPORTED: &[&str] = &[
    "sub", "aud", "exp", "iat", "iss", "jti", "nbf", "ref", "sha", "repository", "repository_id", "repository_owner",
    "repository_owner_id", "enterprise", "run_id", "run_number", "run_attempt", "actor", "actor_id", "workflow", "workflow_ref",
    "workflow_sha", "head_ref", "base_ref", "event_name", "ref_type", "ref_protected", "environment", "job_workflow_ref",
    "job_workflow_sha", "repository_visibility", "runner_environment", "triggering_actor",
];

pub fn routes() -> Router<AppState> {
    Router::new()
        .route(&format!("{ISSUER_PATH}/.well-known/openid-configuration"), get(configuration))
        .route(&format!("{ISSUER_PATH}/.well-known/jwks"), get(jwks))
        .route(&format!("{ISSUER_PATH}/idtoken"), get(id_token).post(id_token))
}

pub fn issuer(s: &AppState) -> String {
    format!("{}{ISSUER_PATH}", s.base_url().trim_end_matches('/'))
}

