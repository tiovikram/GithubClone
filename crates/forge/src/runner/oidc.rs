// Signing key

struct SigningKey {
    kid: String,
    key: KeyPair,
    n: Vec<u8>,
    e: Vec<u8>,
}

static KEY: OnceCell<Arc<SigningKey>> = OnceCell::const_new();

/// One DER TLV (definite lengths only): (tag, content range).
fn der_tlv(buf: &[u8], pos: &mut usize) -> Option<(u8, std::ops::Range<usize>)> {
    let tag = *buf.get(*pos)?;
    let mut p = *pos + 1;
    let first = *buf.get(p)? as usize;
    p += 1;
    let len = if first < 0x80 {
        first
    } else {
        let n = first & 0x7f;
        if n == 0 || n > 4 {
            return None;
        }
        let mut l = 0usize;
        for _ in 0..n {
            l = (l << 8) | *buf.get(p)? as usize;
            p += 1;
        }
        l
    };
    let end = p.checked_add(len)?;
    if end > buf.len() {
        return None;
    }
    *pos = end;
    Some((tag, p..end))
}

/// (n, e) of a PKCS#1 `RSAPublicKey`, without leading zero bytes.
fn rsa_components(pkcs1: &[u8]) -> Option<(Vec<u8>, Vec<u8>)> {
    let mut pos = 0;
    let (t, body) = der_tlv(pkcs1, &mut pos)?;
    if t != 0x30 {
        return None;
    }
    let inner = &pkcs1[body];
    let mut p = 0;
    let (t1, n) = der_tlv(inner, &mut p)?;
    let (t2, e) = der_tlv(inner, &mut p)?;
    if t1 != 0x02 || t2 != 0x02 {
        return None;
    }
    let strip = |b: &[u8]| -> Vec<u8> {
        let i = b.iter().position(|x| *x != 0).unwrap_or(b.len().saturating_sub(1));
        b[i..].to_vec()
    };
    Some((strip(&inner[n]), strip(&inner[e])))
}

async fn load_key(s: &AppState) -> ApiResult<Arc<SigningKey>> {
    KEY.get_or_try_init(|| async {
        let row: Option<(String, Vec<u8>, String)> =
            sqlx::query_as("SELECT kid, public_key, sealed_private_key FROM actions_oidc_keys WHERE id = 1").fetch_optional(&s.db).await?;
        let row = match row {
            Some(r) => r,
            None => {
                let kp = KeyPair::generate(KeySize::Rsa2048).map_err(|_| ApiError::internal("RSA key generation failed"))?;
                let pkcs8 = kp.as_der().map_err(|_| ApiError::internal("RSA key encoding failed"))?;
                let public = kp.public_key().as_ref().to_vec();
                let kid = hex::encode(&Sha256::digest(&public)[..20]).to_uppercase();
                let (_, pk) = crypto::public_key(s, "oidc", 0).await?;
                let sealed = crypto::seal_for(&pk, &B64.encode(pkcs8.as_ref()))?;
                sqlx::query("INSERT INTO actions_oidc_keys (id, kid, public_key, sealed_private_key) VALUES (1, $1, $2, $3) ON CONFLICT DO NOTHING")
                    .bind(&kid)
                    .bind(&public)
                    .bind(&sealed)
                    .execute(&s.db)
                    .await?;
                sqlx::query_as("SELECT kid, public_key, sealed_private_key FROM actions_oidc_keys WHERE id = 1").fetch_one(&s.db).await?
            }
        };
        let (kid, public, sealed) = row;
        let (_, sk) = crypto::private_key(s, "oidc", 0).await?.ok_or_else(|| ApiError::internal("OIDC sealing key missing"))?;
        let pkcs8 = crypto::open_sealed(&sk, &sealed).ok_or_else(|| ApiError::internal("cannot unseal the OIDC signing key"))?;
        let der = B64.decode(pkcs8).map_err(ApiError::internal)?;
        let key = KeyPair::from_pkcs8(&der).map_err(|_| ApiError::internal("bad OIDC signing key"))?;
        let (n, e) = rsa_components(&public).ok_or_else(|| ApiError::internal("bad OIDC public key"))?;
        Ok::<_, ApiError>(Arc::new(SigningKey { kid, key, n, e }))
    })
    .await
    .cloned()
}

fn sign(k: &SigningKey, claims: &Value) -> ApiResult<String> {
    let header = B64URL.encode(serde_json::to_vec(&json!({"typ": "JWT", "alg": "RS256", "x5t": k.kid, "kid": k.kid})).map_err(ApiError::internal)?);
    let payload = B64URL.encode(serde_json::to_vec(claims).map_err(ApiError::internal)?);
    let input = format!("{header}.{payload}");
    let mut sig = vec![0u8; k.key.public_modulus_len()];
    k.key
        .sign(&signature::RSA_PKCS1_SHA256, &aws_lc_rs::rand::SystemRandom::new(), input.as_bytes(), &mut sig)
        .map_err(|_| ApiError::internal("signing failed"))?;
    Ok(format!("{input}.{}", B64URL.encode(sig)))
}

