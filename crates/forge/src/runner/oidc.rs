async fn configuration(State(s): State<AppState>) -> Json<Value> {
    let iss = issuer(&s);
    Json(json!({
        "issuer": iss,
        "jwks_uri": format!("{iss}/.well-known/jwks"),
        "subject_types_supported": ["public", "pairwise"],
        "response_types_supported": ["id_token"],
        "claims_supported": CLAIMS_SUPPORTED,
        "id_token_signing_alg_values_supported": ["RS256"],
        "scopes_supported": ["openid"],
    }))
}

async fn jwks(State(s): State<AppState>) -> ApiResult<Json<Value>> {
    let k = load_key(&s).await?;
    Ok(Json(json!({ "keys": [{
        "kty": "RSA", "alg": "RS256", "use": "sig", "kid": k.kid, "x5t": k.kid,
        "n": B64URL.encode(&k.n), "e": B64URL.encode(&k.e),
    }]})))
}

#[derive(Deserialize)]
struct TokenQuery {
    audience: Option<String>,
}

fn bearer(h: &HeaderMap) -> Option<String> {
    let v = h.get(header::AUTHORIZATION)?.to_str().ok()?.trim();
    let (scheme, cred) = v.split_once(' ')?;
    matches!(scheme.to_ascii_lowercase().as_str(), "bearer" | "token").then(|| cred.trim().to_string())
}

/// Signs an ID token for the job holding the request token.
pub async fn issue(s: &AppState, request_token: &str, audience: Option<&str>) -> ApiResult<String> {
    let row: Option<(Value, String)> = sqlx::query_as(
        "SELECT t.claims, j.status FROM actions_oidc_request_tokens t JOIN actions_jobs j ON j.id = t.job_id
          WHERE t.token_hash = $1 AND t.expires_at > now()",
    )
    .bind(sha256_hex(request_token))
    .fetch_optional(&s.db)
    .await?;
    let Some((claims, status)) = row else { return Err(ApiError::bad_credentials()) };
    if status != "in_progress" {
        return Err(ApiError::bad_credentials());
    }
    let mut c = claims.as_object().cloned().unwrap_or_default();
    let owner = c.get("repository_owner").map(claim_str).unwrap_or_default();
    let aud = audience.map(str::trim).filter(|a| !a.is_empty()).map(str::to_string).unwrap_or_else(|| format!("{}/{owner}", s.base_url().trim_end_matches('/')));
    let now = chrono::Utc::now().timestamp();
    c.insert("jti".into(), json!(uuid::Uuid::new_v4().to_string()));
    c.insert("aud".into(), json!(aud));
    c.insert("iss".into(), json!(issuer(s)));
    c.insert("nbf".into(), json!(now - 5));
    c.insert("iat".into(), json!(now));
    c.insert("exp".into(), json!(now + TOKEN_TTL_SECS));
    let k = load_key(s).await?;
    sign(&k, &Value::Object(c))
}

async fn id_token(State(s): State<AppState>, headers: HeaderMap, Query(q): Query<TokenQuery>) -> ApiResult<Response> {
    let Some(tok) = bearer(&headers) else { return Err(ApiError::unauthorized()) };
    let jwt = issue(&s, &tok, q.audience.as_deref()).await?;
    Ok((StatusCode::OK, Json(json!({ "count": 1, "value": jwt }))).into_response())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn subjects() {
        let mut c = Map::new();
        c.insert("repository".into(), json!("o/r"));
        c.insert("ref".into(), json!("refs/heads/main"));
        c.insert("event_name".into(), json!("push"));
        c.insert("workflow".into(), json!("CI"));
        let d = vec!["repo".to_string(), "context".to_string()];
        assert_eq!(subject(&d, &c), "repo:o/r:ref:refs/heads/main");
        c.insert("event_name".into(), json!("pull_request"));
        assert_eq!(subject(&d, &c), "repo:o/r:pull_request");
        c.insert("environment".into(), json!("prod"));
        assert_eq!(subject(&d, &c), "repo:o/r:environment:prod");
        assert_eq!(subject(&["repo".into(), "workflow".into()], &c), "repo:o/r:workflow:CI");
    }

    #[test]
    fn components() {
        let kp = KeyPair::generate(KeySize::Rsa2048).unwrap();
        let (n, e) = rsa_components(kp.public_key().as_ref()).unwrap();
        assert_eq!(n.len(), 256);
        assert_eq!(e, vec![1, 0, 1]);
    }
}
