/// Whether a job's effective `permissions:` (job, else workflow) grant `id-token: write`.
/// GitHub's default token permissions never include it.
pub fn id_token_allowed(run: &RunRow, job_def: &Value) -> bool {
    let spec = job_def.get("permissions").or_else(|| run.definition.as_ref().and_then(|d| d.get("permissions")));
    match spec {
        Some(Value::String(s)) => s == "write-all",
        Some(Value::Object(o)) => o.get("id-token").and_then(Value::as_str) == Some("write"),
        _ => false,
    }
}

fn claim_str(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}

/// `sub` from the claim keys of the template (`repo`, `context` or any claim name).
pub fn subject(keys: &[String], claims: &Map<String, Value>) -> String {
    let get = |k: &str| claims.get(k).map(claim_str).unwrap_or_default();
    let mut parts: Vec<String> = Vec::new();
    for k in keys {
        match k.as_str() {
            "repo" => parts.push(format!("repo:{}", get("repository"))),
            "context" => {
                let env = get("environment");
                if !env.is_empty() {
                    parts.push(format!("environment:{env}"));
                } else if get("event_name").starts_with("pull_request") {
                    parts.push("pull_request".into());
                } else {
                    parts.push(format!("ref:{}", get("ref")));
                }
            }
            other => parts.push(format!("{other}:{}", get(other))),
        }
    }
    parts.join(":")
}

/// Claims of a job's ID tokens (everything except `aud`, `iat`, `nbf`, `exp`, `jti`).
#[allow(clippy::too_many_arguments)]
pub async fn job_claims(s: &AppState, ctx: &RepoCtx, run: &RunRow, job: &JobRow, github: &Value, environment: Option<&str>) -> ApiResult<Map<String, Value>> {
    let g = |k: &str| claim_str(&github[k]);
    let git_ref = g("ref");
    let ref_protected = match git_ref.strip_prefix("refs/heads/") {
        Some(b) => sqlx::query_scalar::<_, bool>("SELECT EXISTS (SELECT 1 FROM branch_protections WHERE repo_id = $1 AND branch = $2)")
            .bind(ctx.repo.id)
            .bind(b)
            .fetch_one(&s.db)
            .await
            .unwrap_or(false),
        None => false,
    };
    let visibility = if ctx.repo.visibility.is_empty() { if ctx.repo.private { "private" } else { "public" } } else { ctx.repo.visibility.as_str() };
    let full = ctx.full_name();
    let job_workflow_ref = format!("{full}/{}@{git_ref}", run.workflow_path);
    let mut c = Map::new();
    let mut put = |k: &str, v: Value| {
        c.insert(k.to_string(), v);
    };
    put("ref", json!(git_ref));
    put("sha", json!(g("sha")));
    put("repository", json!(full));
    put("repository_owner", json!(ctx.owner.login));
    put("repository_owner_id", json!(ctx.owner.id.to_string()));
    put("run_id", json!(run.id.to_string()));
    put("run_number", json!(run.run_number.to_string()));
    put("run_attempt", json!(job.run_attempt.to_string()));
    put("repository_visibility", json!(visibility));
    put("repository_id", json!(ctx.repo.id.to_string()));
    put("actor_id", json!(g("actor_id")));
    put("actor", json!(g("actor")));
    put("triggering_actor", json!(g("triggering_actor")));
    put("workflow", json!(run.name));
    put("head_ref", json!(g("head_ref")));
    put("base_ref", json!(g("base_ref")));
    put("event_name", json!(run.event));
    put("ref_protected", json!(ref_protected.to_string()));
    put("ref_type", json!(g("ref_type")));
    put("workflow_ref", json!(g("workflow_ref")));
    put("workflow_sha", json!(g("workflow_sha")));
    put("job_workflow_ref", json!(job_workflow_ref));
    put("job_workflow_sha", json!(g("workflow_sha")));
    put("runner_environment", json!("self-hosted"));
    put("enterprise", json!(crate::enterprise::slug()));
    if let Some(e) = environment {
        put("environment", json!(e));
    }
    let keys = crate::api::runner_misc::subject_claim_keys(s, ctx).await?;
    let sub = subject(&keys, &c);
    c.insert("sub".into(), json!(sub));
    Ok(c)
}

/// Creates the job's `ACTIONS_ID_TOKEN_REQUEST_TOKEN` when the job may request ID tokens:
/// `{"path": TOKEN_PATH, "token": ...}` for the job message.
#[allow(clippy::too_many_arguments)]
pub async fn request_token(
    s: &AppState,
    ctx: &RepoCtx,
    run: &RunRow,
    job: &JobRow,
    github: &Value,
    environment: Option<&str>,
    fork_write: bool,
    expires_at: chrono::DateTime<chrono::Utc>,
) -> ApiResult<Option<Value>> {
    if !id_token_allowed(run, &job.definition) {
        return Ok(None);
    }
    // Fork pull requests get no id-token write unless the fork policy sends write tokens.
    let fork = run.head_repo_id.is_some_and(|h| h != run.repo_id);
    if fork && !fork_write {
        return Ok(None);
    }
    let claims = job_claims(s, ctx, run, job, github, environment).await?;
    let token = format!("fid_{}", crate::auth::random_string(40));
    sqlx::query("INSERT INTO actions_oidc_request_tokens (token_hash, job_id, claims, expires_at) VALUES ($1, $2, $3, $4)")
        .bind(sha256_hex(&token))
        .bind(job.id)
        .bind(Value::Object(claims))
        .bind(expires_at)
        .execute(&s.db)
        .await?;
    Ok(Some(json!({ "path": TOKEN_PATH, "token": token })))
}

