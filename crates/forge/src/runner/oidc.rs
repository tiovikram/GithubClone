//! OpenID Connect ID tokens for Actions jobs (GitHub's `token.actions.githubusercontent.com`;
//! on GHES the issuer is `https://HOSTNAME/_services/token`).
//!
//! - A job whose effective `permissions:` grant `id-token: write` gets
//!   `ACTIONS_ID_TOKEN_REQUEST_URL` / `ACTIONS_ID_TOKEN_REQUEST_TOKEN` (the runner puts them in
//!   every step's environment). The request token is random, sha256-stored in
//!   `actions_oidc_request_tokens` with the job's claims, and only works while the job is in
//!   progress (and until the job token's expiry).
//! - `GET {REQUEST_URL}&audience=X` with `Authorization: Bearer {REQUEST_TOKEN}` returns
//!   `{"count": 1, "value": "<jwt>"}`: an RS256 JWT (5 minutes) signed with the site key. `aud`
//!   defaults to the repository owner's URL (`{base}/{owner}`), as on GitHub.
//! - `sub` follows the repository's custom template, else the organization's
//!   (`api::runner_misc::subject_claim_keys`), else `repo:o/r:<context>` where the context is
//!   `environment:<name>`, `pull_request`, or `ref:<ref>`.
//! - Discovery is unauthenticated: `{issuer}/.well-known/openid-configuration` and the JWKS at
//!   `{issuer}/.well-known/jwks`.
//!
//! The signing key is one RSA-2048 key per site (`actions_oidc_keys`, generated by the first pod
//! with `INSERT .. ON CONFLICT DO NOTHING` and re-read, so every pod signs with the same key).
//! Its PKCS#8 private key is sealed (crypto_box) for the X25519 key pair `('oidc', 0)` of
//! `api::actions_settings::crypto`, whose private half is sealed with the master key
//! (`FORGE_SECRET_KEY`), so a database dump alone does not reveal it.
